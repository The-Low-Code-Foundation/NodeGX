/**
 * Build the admin manager app (BMG-001): the browser half of the backend.
 *
 * Two artefacts land in `build/admin/` (gitignored), and `AdminDashboardRoutes`
 * inlines both into the one served document exactly as it inlines `styles.css`:
 *
 *   app.js.txt   the Preact + TSX app in `src/admin/app/`, bundled by esbuild as
 *                one minified IIFE. The `.txt` extension is what makes esbuild's
 *                text loader (scripts/build.js) and jest's text transformer
 *                (tests/text-transformer.js) both read it as a STRING rather
 *                than a module — the page is still one document, zero external
 *                origins, `default-src 'none'`.
 *   tokens.css   core-ui's canonical palette and spacing tokens, copied by THIS
 *                step rather than by hand, so the copy cannot drift again
 *                (BAK-005-NOTES §5 listed the hand copy as a residual; CHR-013
 *                moved the palette and the copy did not follow).
 *
 * `scripts/build.js` runs this first; `tests/global-setup.js` runs it before
 * the jest suite, so a test never grades a stale bundle.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const pkgRoot = path.resolve(__dirname, '..');
const OUT_DIR = path.join(pkgRoot, 'build', 'admin');
const TOKEN_SOURCES = ['colors.css', 'spacing.css'].map((f) =>
  path.join(pkgRoot, '..', 'noodl-core-ui', 'src', 'styles', 'custom-properties', f)
);

/** Comments are most of colors.css; the page ships every byte, so they stay behind. */
function stripComments(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\n\s*\n+/g, '\n')
    .trim();
}

function buildTokens() {
  const header =
    '/* GENERATED by scripts/build-admin-app.js from packages/noodl-core-ui/src/styles/custom-properties/' +
    '{colors,spacing}.css. Do not edit: it is remade on every build (BMG-001 §3.4). */\n';
  const body = TOKEN_SOURCES.map((file) => stripComments(fs.readFileSync(file, 'utf8'))).join('\n');
  fs.writeFileSync(path.join(OUT_DIR, 'tokens.css'), header + body + '\n');
}

async function buildAdminApp() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  buildTokens();
  await esbuild.build({
    entryPoints: [path.join(pkgRoot, 'src', 'admin', 'app', 'main.tsx')],
    bundle: true,
    platform: 'browser',
    target: ['es2020'],
    format: 'iife',
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    charset: 'utf8',
    jsx: 'automatic',
    jsxImportSource: 'preact',
    logLevel: 'warning',
    outfile: path.join(OUT_DIR, 'app.js.txt')
  });
  return OUT_DIR;
}

module.exports = { buildAdminApp, OUT_DIR };

if (require.main === module) {
  buildAdminApp()
    .then((dir) => {
      const js = fs.statSync(path.join(dir, 'app.js.txt')).size;
      const css = fs.statSync(path.join(dir, 'tokens.css')).size;
      process.stdout.write(`admin app built: app.js.txt ${js} bytes, tokens.css ${css} bytes → ${dir}\n`);
    })
    .catch((e) => {
      console.error(e);
      process.exit(1);
    });
}
