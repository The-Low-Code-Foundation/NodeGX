/**
 * Writes src/draw-specs.generated.ts (OWN-012 step 2): the part of each visual spec the drawer reads — every input's
 * `default`, `layout` role and `portability` class, for each type whose spec gives any input a layout role — as data,
 * derived from `src/nodes` through `drawSpecTable` (src/draw.ts). Not hand-copied: tests/draw-specs.test.ts derives
 * the same table from the live specs and fails when this file is stale, so a spec edit that touches a layout role or a
 * default is followed by `node scripts/gen-draw-specs.mjs`. `--check` exits 1 instead of writing when it is stale.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const target = join(pkg, 'src', 'draw-specs.generated.ts');

const dir = mkdtempSync(join(tmpdir(), 'draw-specs-'));
try {
  const out = join(dir, 'derive.cjs');
  await esbuild.build({
    stdin: {
      contents: "import { specs } from './src/nodes'; import { drawSpecTable } from './src/draw'; module.exports = drawSpecTable(specs);",
      resolveDir: pkg,
      loader: 'ts'
    },
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'es2020',
    outfile: out,
    logLevel: 'warning'
  });
  const { default: table } = await import(pathToFileURL(out).href);
  const types = Object.keys(table);
  const text =
    `/**\n * GENERATED by scripts/gen-draw-specs.mjs — do not edit. What the drawer (draw.ts) reads from each visual spec, as data:\n` +
    ` * every input's default, layout role and portability class, for the ${types.length} types whose spec gives an input a layout role.\n` +
    ` * tests/draw-specs.test.ts derives the same table from src/nodes and fails while this file is stale.\n */\n` +
    `import type { DrawSpec } from './draw';\n\nexport const DRAW_SPECS: Readonly<Record<string, DrawSpec>> = ${JSON.stringify(table, null, 2)};\n`;
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      current = '';
    }
    if (current !== text) {
      console.error(`gen-draw-specs: ${target} is stale — run node scripts/gen-draw-specs.mjs`);
      process.exit(1);
    }
    console.log(`gen-draw-specs: ${target} is current (${types.length} types)`);
  } else {
    writeFileSync(target, text);
    console.log(`gen-draw-specs: wrote ${target} (${types.length} types: ${types.join(', ')})`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
