// P125 CCN-008 — writes src/miniEditor/panelSource.ts from the panel's real files (panel/mini-editor.js and .css).
//
// The panel is authored as plain browser files so it can be read and run as it is; the server ships it as strings
// (as companion.ts does), because the bundle carries no loose files. `tests/ccn008MiniEditor.test.ts` fails when the
// two disagree: run `node scripts/embed-mini-editor.cjs` after editing the panel.
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', 'src', 'miniEditor');

function panelSourceText() {
  const js = fs.readFileSync(path.join(dir, 'panel', 'mini-editor.js'), 'utf8');
  const css = fs.readFileSync(path.join(dir, 'panel', 'mini-editor.css'), 'utf8');
  return (
    '// GENERATED by scripts/embed-mini-editor.cjs from panel/mini-editor.js and panel/mini-editor.css. Do not edit.\n' +
    '/* eslint-disable */\n' +
    `export const MINI_EDITOR_JS: string = ${JSON.stringify(js)};\n\n` +
    `export const MINI_EDITOR_CSS: string = ${JSON.stringify(css)};\n\n` +
    '/** The page: the same for every call, valid before anything runs (the host prefetches it). */\n' +
    'export function miniEditorPage(origin: string, id = "", window = true): string {\n' +
    '  const boot = JSON.stringify({ origin, id }).replace(/</g, "\\\\u003c");\n' +
    '  return (\n' +
    '    \'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">\' +\n' +
    '    \'<title>Mini editor</title><style>\' + MINI_EDITOR_CSS + \'</style></head>\' +\n' +
    '    \'<body\' + (window ? \' class="me-window"\' : \'\') + \'><div id="me-root"><p class="me-wait">Opening the mini editor…</p></div>\' +\n' +
    '    \'<script>window.__MINI=\' + boot + \'</script>\' +\n' +
    '    \'<script type="module" src="\' + origin + \'/__nodegx/mini/app.js"></script></body></html>\'\n' +
    '  );\n' +
    '}\n'
  );
}

module.exports = { panelSourceText };

if (require.main === module) {
  fs.writeFileSync(path.join(dir, 'panelSource.ts'), panelSourceText());
  console.log('wrote src/miniEditor/panelSource.ts');
}
