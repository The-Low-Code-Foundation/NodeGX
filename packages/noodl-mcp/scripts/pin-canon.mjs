#!/usr/bin/env node
/**
 * P128 S1 (CCN-009) — copy `docs/CANON.md` into the module both clients read.
 *
 * The canon is the source; the editor and this server cannot read a file outside their bundle at run time (the editor
 * is webpack, this server is one esbuild file on npm), so the sections they quote are pinned as strings in
 * `packages/noodl-editor/src/editor/src/models/canon.ts`. `tests/p128CanonPin.test.ts` diffs the pin against the
 * canon and fails on drift, naming this script. Run it after the canon changes:
 *
 *   node packages/noodl-mcp/scripts/pin-canon.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const CANON = path.join(repo, 'docs/CANON.md');
const OUT = path.join(repo, 'packages/noodl-editor/src/editor/src/models/canon.ts');

/** The headings a surface quotes. Kept in step with `PINNED_HEADINGS` in the test. */
export const PINNED = [
  'What NodeGX is for',
  'Which AI coder',
  'Three ways to touch your app',
  'The wiring underneath',
  'Get the tools',
  'For the agent (the rules, not copy)'
];

/** `## heading` → its body, trimmed, for every second-level section of `text`. */
export function canonSections(text) {
  const out = {};
  for (const block of text.split(/^## /m).slice(1)) {
    const nl = block.indexOf('\n');
    out[block.slice(0, nl).trim()] = block.slice(nl + 1).trim();
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const sections = canonSections(fs.readFileSync(CANON, 'utf8'));
  const missing = PINNED.filter((h) => !(h in sections));
  if (missing.length) {
    console.error(`docs/CANON.md has no section ${missing.map((h) => `"${h}"`).join(', ')}.`);
    process.exit(1);
  }
  const body = PINNED.map((h) => `  ${JSON.stringify(h)}:\n    ${JSON.stringify(sections[h])}`).join(',\n');
  const ts = `/**
 * P128 — the canon, pinned: the sections of \`docs/CANON.md\` a surface quotes, word for word.
 *
 * ⚠️ Generated by \`node packages/noodl-mcp/scripts/pin-canon.mjs\`; do not edit by hand. Change the words in
 * \`docs/CANON.md\` (Richard rules them) and run the script. \`packages/noodl-mcp/tests/p128CanonPin.test.ts\` fails
 * when this file and the canon disagree.
 *
 * Imports nothing, so \`noodl-mcp/src/editor-deps.ts\` re-exports it and both clients carry the same bytes.
 */
export const CANON = {
${body}
} as const;

export type CanonHeading = keyof typeof CANON;
`;
  fs.writeFileSync(OUT, ts);
  console.log(`pinned ${PINNED.length} sections → ${path.relative(repo, OUT)}`);
}
