#!/usr/bin/env node
/**
 * P128 S6 (STU-084) — copy NodeGX Studio's vocabulary into this server.
 *
 * Studio says what it draws and edits in one file, `nodegx-studio/editor/vocabulary.json` (its element types, its
 * action menu, the value sources it chips), and reads its own copy of nothing: studio.html takes those lists from it.
 * This server ships as one esbuild file and cannot read Studio's checkout at run time, so the file is pinned as
 * `src/studio/studioVocabulary.ts`; `tests/p128StudioVocabulary.test.ts` diffs the pin against Studio's file when a
 * Studio checkout is beside this one, and fails on drift naming this script. Run it after Studio's vocabulary changes:
 *
 *   node packages/noodl-mcp/scripts/pin-studio-vocabulary.mjs [path/to/nodegx-studio]
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'studio', 'studioVocabulary.ts');
const studio = process.argv[2] ?? process.env.NODEGX_STUDIO ?? path.join(os.homedir(), 'vscode_projects', 'nodegx-studio');
const file = path.join(studio, 'editor', 'vocabulary.json');
const vocab = JSON.parse(fs.readFileSync(file, 'utf8'));

fs.writeFileSync(
  OUT,
  `/**
 * GENERATED by \`scripts/pin-studio-vocabulary.mjs\` from NodeGX Studio's \`editor/vocabulary.json\` — do not edit.
 * What Studio draws and edits (STU-084); \`vocabulary.ts\` reads its lists from here. The test
 * \`tests/p128StudioVocabulary.test.ts\` fails when this differs from Studio's file.
 */
/* eslint-disable */
export const STUDIO_VOCABULARY = ${JSON.stringify(vocab, null, 2)} as const;
`
);
console.log(`pinned ${path.relative(process.cwd(), OUT)} from ${file}`);
