/**
 * P134 session 13, Richard's R8 ("a little React just to run the kits is totally justifiable"). The React export's kit
 * bridge (`kits.ts` `runtimeFile()`, EXP-010 Route B: `window.React`, `Noodl.defineModule`, the node object a kit's code
 * runs against, `KitNode`) as the HTML export's `lib/kits.js`: the same text, its types out, React read from the global
 * build `index.html` loads (`lib/vendor/react.production.min.js`), its one JSX element written as `createElement`. In
 * addition `mountKitNode(l, parent, before, type, params, signals, values)` renders one kit node into a box with
 * `ReactDOM.createRoot`, again whenever what `params()` reads changes, and unmounts it when the part goes.
 */
export function htmlKitsJs(): string {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { runtimeFile } = require('../../src/emit/kits') as { runtimeFile: () => string };
  const full = runtimeFile();
  const reactImport = "import * as React from 'react';\n";
  const jsx = 'return <span hidden data-nodegx-missing-kit-node={type} />;';
  if (!full.includes(reactImport) || !full.includes(jsx)) throw new Error("the kit bridge no longer reads as it did: the HTML export's copy must be cut again");
  const src = full
    .replace(/^\/\/ @nodegx:generated[^\n]*\n/, '')
    .replace(reactImport, "// React is the global build index.html loads before the app (lib/vendor/react.production.min.js).\nconst React = window.React;\n")
    .replace(jsx, "return React.createElement('span', { hidden: true, 'data-nodegx-missing-kit-node': type });");
  const plain = [
    '',
    '// ---- in a plain page -------------------------------------------------------------------------------',
    '',
    '/**',
    ' * One kit node in a plain page: a box in `parent` (before `before`), `display: contents` so the kit\'s own element',
    ' * lays out as the node does, rendered by React (`lib/vendor/react-dom.production.min.js`). `params()` gives its inputs',
    ' * by port name; it is read again, and the node rendered again, whenever a value it reads changes. `signals` and',
    ' * `values` are its outputs, by port name. When the part goes, React unmounts it and the box is removed.',
    ' */',
    'export function mountKitNode(l, parent, before, type, params, signals, values) {',
    "  const box = document.createElement('div');",
    "  box.style.display = 'contents';",
    '  parent.insertBefore(box, before || null);',
    '  const root = window.ReactDOM.createRoot(box);',
    '  l.run(function () {',
    '    root.render(React.createElement(KitNode, { type: type, params: params(), signals: signals, values: values }));',
    '  });',
    '  l.add(function () {',
    '    root.unmount();',
    '    box.remove();',
    '  });',
    '  return box;',
    '}',
    ''
  ].join('\n');
  return plainJs("// Generated by the export: the kit bridge, the same file the React export carries, its types out.\n" + src + plain);
}

