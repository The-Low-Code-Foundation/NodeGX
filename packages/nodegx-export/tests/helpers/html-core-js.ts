/**
 * P134 HTX-001. `@nodegx/core` as one plain JavaScript file a person reads top to bottom: the `lib/core.js` every HTML
 * export carries (`src/emit/html/coreJs.ts`).
 *
 * The core's own source, with only its types taken out: Node's `module.stripTypeScriptTypes` (strip mode, so every
 * comment and every line the author wrote stays where it was), the files joined in the order they depend on each other,
 * their imports between one another removed, and one `export { … }` at the end naming what `index.ts` exports. Prettier
 * then closes the gaps the types left. The React binding (`react.ts`) and its selector helper are not carried.
 *
 * The exporter carries no TypeScript and no `@nodegx/core` when installed, so the file travels as a constant, as the
 * Swift target's does (`tests/helpers/swift-core-js.ts`). This is the one place the constant is made:
 * `tests/html-the-first-page.test.ts` makes it again from the core's source and fails when the two differ.
 *
 *   cd packages/nodegx-export && npx ts-node --transpile-only -O '{"module":"commonjs"}' tests/helpers/html-core-js.ts
 *
 * writes the constants (`coreJs.ts`; `functionRunJs.ts`, `statesJs.ts` and `persistStoreJs.ts`, P134 HTX-002).
 */

import * as fs from 'fs';
import * as path from 'path';
// Node ≥ 22.13: types out, every other character where it was.
// eslint-disable-next-line @typescript-eslint/no-var-requires
const { stripTypeScriptTypes } = require('node:module') as { stripTypeScriptTypes: (code: string, options: { mode: 'strip' }) => string };
// eslint-disable-next-line @typescript-eslint/no-var-requires
const prettier = require('prettier') as { format: (code: string, options: Record<string, unknown>) => string };

export const CORE_SRC = path.join(__dirname, '..', '..', '..', 'nodegx-core', 'src');

/** Each file after the ones it imports. */
const ORDER = ['internal', 'value', 'derived', 'signal', 'store', 'collection', 'events', 'effect'];

/** What `index.ts` exports, read from it, types apart. */
function publicNames(dir: string): string[] {
  const index = fs.readFileSync(path.join(dir, 'index.ts'), 'utf-8');
  const names: string[] = [];
  for (const m of index.matchAll(/^export \{([^}]*)\} from/gm)) {
    for (const raw of m[1].split(',')) {
      const name = raw.trim();
      if (name && !name.startsWith('type ')) names.push(name);
    }
  }
  return names;
}

export function htmlCoreJs(dir = CORE_SRC): string {
  const present = fs.readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts' && f !== 'react.ts' && f !== 'selector.ts');
  const missing = present.map((f) => f.replace(/\.ts$/, '')).filter((f) => !ORDER.includes(f));
  if (missing.length > 0) throw new Error(`@nodegx/core has ${missing.join(', ')}, which lib/core.js does not place yet: add it to ORDER`);
  const parts = ORDER.map((base) => {
    const js = stripTypeScriptTypes(fs.readFileSync(path.join(dir, `${base}.ts`), 'utf-8'), { mode: 'strip' })
      // A doc comment over an interface or a type, which strip mode leaves as a line of spaces: it describes nothing now.
      .replace(/\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n(?=[ \t]+\n)/g, '')
      // The files are one file now: what one imported from another is already in scope.
      .replace(/^import [^;]*;\n/gm, '')
      .replace(/^export \{[^}]*\} from [^;]*;\n/gm, '')
      .replace(/^export (?=(function|class|const|let)\b)/gm, '');
    return `// ---- ${base}.ts ----\n\n${js.trim()}\n`;
  });
  const head = [
    '/**',
    ' * @nodegx/core: the values the page reads and the effects that redraw it when they change.',
    ' *',
    ' * This is the source of the npm package `@nodegx/core`, its types taken out and its files joined into one, so the',
    ' * app needs nothing installed. `value(x)` holds a value; `effect(fn)` runs `fn` now and again whenever a value it',
    ' * read changes; `derived(fn)` is a value computed from others. The rest is the machinery they share.',
    ' *',
    ' * Generated by the export, the same in every app. Change it if you like: nothing reads it but your own files.',
    ' */',
    ''
  ].join('\n');
  const text = `${head}\n${parts.join('\n')}\nexport { ${publicNames(dir).join(', ')} };\n`;
  return prettier.format(text, { parser: 'babel', singleQuote: true, printWidth: 120, trailingComma: 'none' });
}

/** The module `src/emit/html/coreJs.ts`. */
export function htmlCoreJsModule(): string {
  return [
    '/**',
    " * P134 HTX-001. `@nodegx/core` as the HTML export's `lib/core.js`: the core's own source, types out, one file.",
    ' *',
    ' * 🔴 Generated, never edited: `tests/helpers/html-core-js.ts` makes it from `packages/nodegx-core/src` (the React',
    ' * binding apart). `tests/html-the-first-page.test.ts` makes it again and fails when the two differ.',
    ' *',
    ' * @module emit/html/coreJs',
    ' */',
    '',
    `export const CORE_JS = ${JSON.stringify(htmlCoreJs())};`,
    ''
  ].join('\n');
}

/**
 * P134 HTX-002. The React export's Function runner (`src/lib/functionRun.ts`, written by `functionRunLibSource`) as the
 * HTML export's `lib/functionRun.js`: the same file, its types taken out the same way, so a Function's run publishes its
 * outputs and its signals in a plain page exactly as it does in the React app.
 */
export function htmlFunctionRunJs(): string {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { functionRunLibSource } = require('../../src/emit/functionRunLib') as { functionRunLibSource: () => string };
  const js = stripTypeScriptTypes(functionRunLibSource(), { mode: 'strip' })
    .replace(/\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n(?=[ \t]+\n)/g, '')
    .replace(/^[ \t]*\/\/ eslint-disable-next-line[^\n]*\n/gm, '');
  const head = '// Generated by the export, the same in every app: how a Function node runs, as the running app runs it.\n\n';
  return prettier.format(head + js, { parser: 'babel', singleQuote: true, printWidth: 120, trailingComma: 'none' });
}

/** Strip mode, a doc comment over a type gone, the lint lines gone, then Prettier: the readable JavaScript of a lib source. */
function plainJs(ts: string): string {
  const js = stripTypeScriptTypes(ts, { mode: 'strip' })
    .replace(/\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n(?=[ \t]+\n)/g, '')
    .replace(/^[ \t]*\/\/ eslint-disable-next-line[^\n]*\n/gm, '');
  return prettier.format(js, { parser: 'babel', singleQuote: true, printWidth: 120, trailingComma: 'none' });
}

/** Cuts `source` at the doc comment above `marker` (a hook), keeping what comes before. */
function before(source: string, marker: string): string {
  const at = source.indexOf(marker);
  if (at < 0) throw new Error(`the library no longer has ${JSON.stringify(marker)}: the HTML export's copy must be cut again`);
  const doc = source.lastIndexOf('/**', at);
  const sep = source.lastIndexOf('// ---- ', at);
  return source.slice(0, Math.max(doc, sep)).trimEnd() + '\n';
}

/**
 * P134 HTX-002. The React export's States node and the run engine it moves along (`statesLib.ts`, `animateLib.ts`), as
 * the HTML export's `lib/states.js` and `lib/animate.js`: the same machine, its types out, the React hooks cut off. In
 * their place `statesNode(def, start, listeners)` keeps the snapshot a page reads in a value, as `useStates` keeps it in
 * React state. The machine is shared, not copied: a change to it reaches both exports, or the spec turns red.
 */
export function htmlAnimateJs(): string {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { animateLibSource } = require('../../src/emit/animateLib') as { animateLibSource: () => string };
  const src = before(animateLibSource(), 'export function useAnimatedValue(').replace("import { useEffect, useRef, useState } from 'react';\n", '');
  return plainJs('// Generated by the export, the same in every app: the run a States move eases along.\n' + src);
}

export function htmlStatesJs(): string {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { statesLibSource } = require('../../src/emit/statesLib') as { statesLibSource: () => string };
  const src = before(statesLibSource(), '// ---- the hook')
    .replace("import { useEffect, useRef, useState } from 'react';\n", "import { value } from './core.js';\n")
    // `Run` is a type: strip mode keeps a type named inside a plain import, and the module has no such export.
    .replace("import { Run, createRun,", 'import { createRun,')
    .replace("from './animate';", "from './animate.js';");
  const plain = [
    '',
    '// ---- in a plain page -------------------------------------------------------------------------------',
    '',
    '/**',
    ' * A States node in a plain page: the machine above, and the snapshot a page reads (`node.get().state`,',
    ' * `node.get().values.x`), a value that changes whenever the machine publishes. `listeners` are its signal outputs.',
    ' */',
    'export function statesNode(def, start, listeners) {',
    '  const m = createStatesMachine(def, start, function () {',
    '    return listeners || {};',
    '  });',
    '  const snapshot = value(snapshotOf(m));',
    '  m.publish = function () {',
    '    snapshot.set(snapshotOf(m));',
    '  };',
    '  return {',
    '    get() {',
    '      return snapshot.get();',
    '    },',
    '    goTo(state) {',
    '      scheduleGoToState(m, state, true);',
    '    },',
    '    toggle() {',
    '      toggleState(m);',
    '    },',
    '    follow(state) {',
    '      scheduleGoToState(m, state, false);',
    '    },',
    '    stop() {',
    '      stopRun(m.run);',
    '    }',
    '  };',
    '}',
    ''
  ].join('\n');
  return plainJs('// Generated by the export, the same in every app: the States node, as the running app moves it.\n' + src + plain);
}

