/**
 * `src/lib/componentScope.ts` — the `Component` a Function node's body is handed (EXP-020 slice 2, session 135).
 *
 * Emitted only where a printed Function reads `Component.Object`. The shape of {@link ./functionRunLib.ts}: constant
 * text, transcribed from two runtime files, shipped where something calls into it.
 *
 * - `noodl-runtime/src/javascriptnodeparser.js` `getComponentScopeForNode` — one scope per component **instance**,
 *   cached by its instance id and handed to every Function in it; its `Object` is `Model.get('componentState' +
 *   instanceId)`, which boots empty. As a hook: the component keeps one scope per mount (`useState`), and each kept
 *   Function node carries it (`functionNode(signals, scope)`), so the instance's Functions share one record.
 * - `noodl-runtime/src/model.ts` — the record itself: `new Model(id, {})` behind `_modelProxyHandler`. `get(name)` /
 *   `set(name, value)` with their `resolve` / `silent` / `forceChange` arguments, `setAll`, `fill`, `on` / `off` /
 *   `notify`, `getId`, `toJSON`, verbatim; and the proxy: a method reads bound, a field of the record (`id`, `data`,
 *   `listeners`) reads as itself, any other name reads `get(name)`; a write is `set(name, value)`, but `id`, which is
 *   read-only and warns.
 *
 * ⚠️ **Recorded divergences:** the id's counter is this app's count of scopes, not the running app's count of component
 * instances, so the text after `componentState__$ndl_componentInstaceId` differs (each is unique all the same); the
 * record's `constructor` is `Object`, not `Model`; and nothing else holds the record — a component with a Component Object
 * family node exports no Function that reads it (plan.ts `COMPONENT_RECORD_FAMILY`).
 */

/** Where the module lands in the exported app. */
export const COMPONENT_SCOPE_LIB_PATH = 'src/lib/componentScope.ts';

/**
 * The module's source.
 *
 * ⚠️ A plain string array rather than a template literal, for `dateLib.ts`'s stated reason.
 */
export function componentScopeLibSource(): string {
  return [
    '//',
    "// The `Component` a Function's body is handed, transcribed from the interpreter it has to agree with:",
    '// noodl-runtime/src/javascriptnodeparser.js (getComponentScopeForNode) and noodl-runtime/src/model.ts (the record).',
    '//',
    "// createComponentScope(): one per component instance, shared by its Functions. `Object` is the instance's record,",
    "// booting empty: `get(name)` and `set(name, value)`, or as properties — `Component.Object.x` reads `get('x')` and",
    "// `Component.Object.x = v` is `set('x', v)`. Its id is read-only.",
    '//',
    '',
    '/* eslint-disable @typescript-eslint/no-explicit-any */',
    '',
    'type Listener = (args?: unknown) => void;',
    '',
    "/** One component instance's record — the running app's `componentState<instanceId>` model. */",
    'export interface ComponentRecord {',
    '  readonly id: string;',
    '  data: Record<string, unknown>;',
    '  get(name: string, args?: { resolve?: boolean }): any;',
    '  set(name: string, value: unknown, args?: { resolve?: boolean; silent?: boolean; forceChange?: boolean }): void;',
    '  setAll(obj: Record<string, unknown>): void;',
    '  fill(value?: unknown): void;',
    '  on(event: string, listener: Listener): void;',
    '  off(event: string, listener: Listener): void;',
    '  notify(event: string, args?: unknown): void;',
    '  getId(): string;',
    '  toJSON(): Record<string, unknown>;',
    '  [name: string]: any;',
    '}',
    '',
    "/** The `Component` a Function's body reads. */",
    'export interface ComponentScope {',
    '  Object: ComponentRecord;',
    '}',
    '',
    '// model.ts `Model.prototype`, verbatim but for the types.',
    'const recordPrototype: Record<string, any> = {',
    '  on(this: any, event: string, listener: Listener) {',
    '    if (!this.listeners) this.listeners = {};',
    '    if (!this.listeners[event]) this.listeners[event] = [];',
    '    this.listeners[event].push(listener);',
    '  },',
    '  off(this: any, event: string, listener: Listener) {',
    '    if (!this.listeners) return;',
    '    if (!this.listeners[event]) return;',
    '    const idx = this.listeners[event].indexOf(listener);',
    '    if (idx !== -1) this.listeners[event].splice(idx, 1);',
    '  },',
    '  notify(this: any, event: string, args?: unknown) {',
    '    if (!this.listeners) return;',
    '    if (!this.listeners[event]) return;',
    '    const l = this.listeners[event].slice(); // clone in case listeners array is modified in the callbacks',
    '    for (let i = 0; i < l.length; i++) l[i](args);',
    '  },',
    '  setAll(this: any, obj: Record<string, unknown>) {',
    '    for (const i in obj) {',
    "      if (i === 'id') continue; // Skip id",
    '      if (this.data[i] !== obj[i]) {',
    '        const old = this.data[i];',
    '        this.data[i] = obj[i];',
    "        this.notify('change', { name: i, value: obj[i], old: old });",
    '      }',
    '    }',
    '  },',
    '  fill(this: any, value: unknown = null) {',
    '    for (const key in this.data) {',
    "      if (key === 'id') continue; // Skip id",
    '      const temp = this.data[key];',
    '      this.data[key] = value;',
    "      this.notify('change', { name: key, value: this.data[key], old: temp });",
    '    }',
    '  },',
    '  set(this: any, name: string, value: unknown, args?: { resolve?: boolean; silent?: boolean; forceChange?: boolean }) {',
    "    if (args && args.resolve && name.indexOf('.') !== -1) {",
    '      // We should resolve path references',
    "      const path = name.split('.');",
    '      let model: any = this;',
    '      for (let i = 0; i < path.length - 1; i++) {',
    '        const v = model.get(path[i]);',
    '        if (isRecord(v)) model = v;',
    '        else return; // Path resolve failed',
    '      }',
    '      model.set(path[path.length - 1], value);',
    '      return;',
    '    }',
    '    const forceChange = args && args.forceChange;',
    '    const oldValue = this.data[name];',
    '    this.data[name] = value;',
    "    if ((forceChange || oldValue !== value) && (!args || !args.silent)) this.notify('change', { name: name, value: value, old: oldValue });",
    '  },',
    '  getId(this: any) {',
    '    return this.id;',
    '  },',
    '  get(this: any, name: string, args?: { resolve?: boolean }) {',
    "    if (args && args.resolve && name.indexOf('.') !== -1) {",
    '      // We should resolve path references',
    "      const path = name.split('.');",
    '      let model: any = this;',
    '      for (let i = 0; i < path.length - 1; i++) {',
    '        const v = model.get(path[i]);',
    '        if (isRecord(v)) model = v;',
    '        else return; // Path resolve failed',
    '      }',
    '      return model.get(path[path.length - 1]);',
    '    }',
    '    return this.data[name];',
    '  },',
    '  toJSON(this: any) {',
    '    return Object.assign({}, this.data, { id: this.id });',
    '  }',
    '};',
    '',
    '// model.ts `Model.instanceOf`: the record, or a proxy over one.',
    'function isRecord(value: unknown): boolean {',
    "  return typeof value === 'object' && value !== null && Object.prototype.isPrototypeOf.call(recordPrototype, value);",
    '}',
    '',
    '// model.ts `_modelProxyHandler`, verbatim but for the types.',
    'const recordProxyHandler: ProxyHandler<any> = {',
    '  get(target, prop, receiver) {',
    '    const member = target[prop];',
    "    if (typeof member === 'function') return member.bind(target);",
    '    else if (prop in target) return Reflect.get(target, prop, receiver);',
    '    else return target.get(prop as string);',
    '  },',
    '  set(obj, prop, value) {',
    "    if (prop === '_class') {",
    '      obj._class = value;',
    "    } else if (prop === 'id') {",
    '      console.log(`Noodl.Object warning: id is readonly (Id is ${obj.id}, trying to set to ${value})`);',
    '      return true; // if a proxy does not return true an exception will be thrown',
    '    } else {',
    '      obj.set(prop as string, value);',
    '    }',
    '    return true;',
    '  },',
    '  ownKeys(target) {',
    '    return Reflect.ownKeys(target.data);',
    '  },',
    '  getOwnPropertyDescriptor(target, prop) {',
    '    return Object.getOwnPropertyDescriptor(target.data, prop);',
    '  }',
    '};',
    '',
    '// componentinstance.ts mints `__$ndl_componentInstaceId<n>`, spelling included.',
    'let scopeCounter = 0;',
    '',
    '/** One component instance\'s `Component`: its record, booting empty. */',
    'export function createComponentScope(): ComponentScope {',
    '  scopeCounter += 1;',
    '  const record = Object.create(recordPrototype);',
    "  record.id = 'componentState' + '__$ndl_componentInstaceId' + scopeCounter;",
    '  record.data = {};',
    '  return { Object: new Proxy(record, recordProxyHandler) as ComponentRecord };',
    '}',
    ''
  ].join('\n');
}
