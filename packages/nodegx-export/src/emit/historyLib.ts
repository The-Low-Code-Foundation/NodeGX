    '  undo(): void;',
    '  /** Redo: steps the store forward one entry. */',
    '  redo(): void;',
    '  /** Jump To: moves the store to the entry Target Index names (read at the pulse). */',
    '  jumpTo(targetIndex?: unknown): void;',
    '  readonly fullyRestorable: boolean;',
    '  readonly byReferenceKeys: string;',
    '  readonly error: string | undefined;',
    '}',
    '',
    'export interface UndoRedoNode extends UndoRedoHandle {',
