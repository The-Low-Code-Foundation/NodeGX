    '/**',
    ' * useStateHistory: one tracker per mount. It attaches after mount (the runtime attaches once the node is in a',
    ' * scope, whether or not anything was authored) and reconfigures in place when an option changes, keeping the',
    ' * history. Unmounting detaches; the last tracker of a store out releases its history.',
    ' */',
    'export function useStateHistory<T extends object>(source: HistoryNodeSource, options: StateHistoryInputs<T>, on: StateHistoryListeners = {}): StateHistoryHandle {',
    '  const [, publish] = useReducer((n: number) => n + 1, 0);',
    '  const nodeRef = useRef<StateHistoryNode | null>(null);',
    '  const appliedRef = useRef(new Map<string, unknown>());',
    '  const changedRef = useRef(0);',
    '  if (nodeRef.current === null) nodeRef.current = createStateHistoryNode(source, storeOf(options.store), () => publish());',
    '  const node = nodeRef.current;',
    '  const inputs = { trackKeys: options.trackKeys, maxHistory: options.maxHistory, coalesceMs: options.coalesceMs, enabled: options.enabled };',
    '  applyInputs(appliedRef.current, inputs, (port, value) => {',
    '    node.setInput(port, value);',
    '    changedRef.current++;',
    '  });',
    '  node.setListeners(on);',
    '',
    '  const changes = changedRef.current;',
    '  useEffect(() => {',
    '    node.setupTracking();',
    '  }, [node, changes]);',
    '',
    '  useEffect(() => {',
    '    return () => {',
    '      node.dispose();',
    '    };',
    '    // eslint-disable-next-line react-hooks/exhaustive-deps -- the node is created once',
    '  }, []);',
    '',
    '  return node;',
    '}',
