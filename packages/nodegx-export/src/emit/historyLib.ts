    'export function createStateSnapshotNode(source: HistoryNodeSource, store: AnyStore, rerender: () => void = () => undefined, manager: StateHistoryManager = stateHistoryManager): StateSnapshotNode {',
    '  const s = {',
    '    snapshotName: undefined as unknown,',
    '    snapshotData: undefined as unknown,',
    '    snapshot: undefined as StoreSnapshot | undefined,',
    '    error: undefined as string | undefined,',
    '    listeners: {} as StateSnapshotListeners',
    '  };',
    '',
    '  const adopt = (snapshot: StoreSnapshot) => {',
    '    s.snapshot = snapshot;',
    '    rerender();',
    '  };',
    '',
    '  /**',
    '   * setError: the Error string and its raise, deduplicated (a repeat of the same message announces nothing); the',
    '   * Failure is owed per invocation, so it is settled outside the dedupe. A clear is not a failure.',
    '   */',
    '  const setError = (message: string | undefined) => {',
    '    const repeat = s.error === message;',
    '    if (!repeat) {',
    '      s.error = message;',
    '      rerender();',
    '      if (message !== undefined) {',
    '        raiseAppError({ code: SNAPSHOT_ERROR_CODE, message, nodeId: source.nodeId, nodeType: SNAPSHOT_TYPE, componentName: source.componentName });',
    '      }',
    '    }',
    '    if (message === undefined) return;',
    '    reportOutcome(source, SNAPSHOT_TYPE, s.listeners as never, \'failure\', { code: SNAPSHOT_ERROR_CODE, message, raise: false });',
    '  };',
    '',
    '  const named = (snapshotName: unknown) => {',
    '    if (snapshotName !== undefined) s.snapshotName = snapshotName;',
    '  };',
    '',
    '  return {',
    '    setInput(_port, value) {',
    '      s.snapshotData = value;',
    '    },',
    '    setListeners(on) {',
    '      s.listeners = on;',
    '    },',
    '    save(snapshotName) {',
    '      named(snapshotName);',
    '      try {',
    '        const snapshot = manager.saveNamedSnapshot(s.snapshotName as string, store);',
    '        adopt(snapshot);',
    '        setError(undefined);',
    '        s.listeners.saved?.();',
    '        reportOutcome(source, SNAPSHOT_TYPE, s.listeners as never, \'done\');',
    '      } catch (error) {',
    '        setError(String((error as Error).message || error));',
    '      }',
    '    },',
    '    restore(snapshotName) {',
    '      named(snapshotName);',
    '      try {',
    '        const data = s.snapshotData;',
    '        const hasData = data !== undefined && data !== null && data !== \'\';',
    '        const snapshot = hasData ? manager.restoreSnapshotData(data, store) : manager.restoreNamedSnapshot(s.snapshotName as string, store);',
    '        adopt(snapshot);',
    '        setError(undefined);',
    '        s.listeners.restored?.();',
    '        reportOutcome(source, SNAPSHOT_TYPE, s.listeners as never, \'done\');',
    '      } catch (error) {',
    '        setError(String((error as Error).message || error));',
    '      }',
    '    },',
    '    get snapshot() {',
    '      return s.snapshot;',
    '    },',
    '    get fullyRestorable() {',
    '      return s.snapshot ? s.snapshot.byReference.length === 0 : true;',
    '    },',
    '    get byReferenceKeys() {',
    '      return s.snapshot ? s.snapshot.byReference.join(\',\') : \'\';',
    '    },',
    '    get error() {',
    '      return s.error;',
    '    }',
    '  };',
    '}',
