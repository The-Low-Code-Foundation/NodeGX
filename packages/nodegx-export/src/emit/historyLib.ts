    'export function createUndoRedoNode(source: HistoryNodeSource, store: AnyStore, rerender: () => void = () => undefined, manager: StateHistoryManager = stateHistoryManager): UndoRedoNode {',
    '  const s = {',
    '    storeName: normalizeName(store.name),',
    '    targetIndex: 0,',
    '    byReferenceKeys: \'\',',
    '    error: undefined as string | undefined,',
    '    listeners: {} as UndoRedoListeners',
    '  };',
    '',
    '  const setError = (message: string | undefined) => {',
    '    if (s.error === message) return;',
    '    s.error = message;',
    '    rerender();',
    '  };',
    '',
    '  const report = (signal: \'undone\' | \'redone\' | \'jumped\', result: HistoryNavigation | null) => {',
    '    if (result === null) {',
    '      reportOutcome(source, UNDO_TYPE, s.listeners as never, \'unchanged\');',
    '      return;',
    '    }',
    '    setError(undefined);',
    '    s.byReferenceKeys = result.byReferenceKeys.join(\',\');',
    '    rerender();',
    '    s.listeners[signal]?.();',
    '    reportOutcome(source, UNDO_TYPE, s.listeners as never, \'done\');',
    '  };',
    '',
    '  /** runQueued for one action: an untracked store is a failure that says so. */',
    '  const run = (action: \'undo\' | \'redo\' | \'jumpTo\') => {',
    '    if (!manager.isTracking(s.storeName)) {',
    '      const message = `No State History node is tracking store "${s.storeName}"`;',
    '      setError(message);',
    '      reportOutcome(source, UNDO_TYPE, s.listeners as never, \'failure\', { code: UNDO_ERROR_CODE, message });',
    '      return;',
    '    }',
    '    if (action === \'undo\') {',
    '      report(\'undone\', manager.undo(s.storeName));',
    '    } else if (action === \'redo\') {',
    '      report(\'redone\', manager.redo(s.storeName));',
    '    } else {',
    '      const index = s.targetIndex;',
    '      const result = manager.jumpTo(s.storeName, index);',
    '      if (result === null) {',
    '        const message = `Target index ${index} is outside the history`;',
    '        setError(message);',
