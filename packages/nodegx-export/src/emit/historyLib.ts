    '  /** Save: copies the store as it is now and keeps it under Snapshot Name (read at the pulse). */',
    '  save(snapshotName?: unknown): void;',
    '  /** Restore: puts a checkpoint back as an ordinary write. Snapshot Data wins over the name. */',
