    '/** Runs a node\'s setter for each option that arrived with a value different from the last one applied. */',
    'function applyInputs<P extends string>(applied: Map<string, unknown>, options: { [K in P]?: unknown }, set: (port: P, value: unknown) => void): void {',
    '  for (const port of Object.keys(options) as P[]) {',
    '    const value = options[port];',
    '    if (value === undefined) continue;',
    '    if (applied.has(port) && Object.is(applied.get(port), value)) continue;',
    '    applied.set(port, value);',
    '    set(port, value);',
    '  }',
