/**
 * P134 HTX-001. The two small files every HTML export carries beside `lib/core.js`, the same in every app:
 *
 * - `lib/dom.js`: what a component does to the page. Make an element, write a value into it now and again whenever the
 *   value changes, mount a part only while a value is true, and undo all of it when the part goes.
 * - `lib/router.js`: which page is showing, read from the address after `#`, so the app works from any folder on any
 *   static server (a refresh on `#/remix` asks the server for `index.html`, which every server has).
 *
 * Plain JavaScript a person reads: no backticks and no `${` in the text, because it lives in a template literal here.
 *
 * @module emit/html/libJs
 */

export const DOM_JS = `/**
 * What a component does to the page, in a few small helpers.
 *
 * Every component file calls these. A component keeps one "life" (made by \`life()\`): each binding it makes is added to
 * it, and \`destroy()\` stops them all, so a part that is taken off the page leaves nothing running behind it.
 *
 * Generated by the export, the same in every app.
 */

import { effect, untracked, value } from './core.js';

/** What a Text shows for a value: nothing for no value, the value as text otherwise. */
export function show(value) {
  return value === undefined || value === null ? '' : String(value);
}

/** The truth of a value, as the running app reads it: false, 0, '', null and undefined are false. */
export function truthy(value) {
  return !!value;
}

/**
 * A value a component keeps (an input, a piece of state). It tells the code that reads it only when it changes: setting
 * the value it already holds does nothing, so nothing runs again for it.
 */
export function keep(initial) {
  const held = value(initial);
  return {
    get() {
      return held.get();
    },
    peek() {
      return held.peek();
    },
    set(next) {
      if (!Object.is(next, held.peek())) held.set(next);
    }
  };
}

/**
 * One key of a Global Store, as a component reads it (a Subscribe of that key): a value that follows \`store\`'s key and,
 * like \`keep\`, tells its readers only when the key holds a different value. A write to another key changes nothing here.
 */
export function storeKey(l, store, key) {
  const held = keep(untracked(function () {
    return store.get()[key];
  }));
  l.run(function () {
    const next = store.get()[key];
    untracked(function () {
      held.set(next);
    });
  });
  return held;
}

/**
 * A component's life: the effects and the parts it made, stopped together.
 * \`run(fn)\` runs fn now and again whenever a value it read changes, until the life ends.
 * \`watch(read, act)\` runs \`act\` now and again whenever one of the values \`read()\` lists is a different value; what \`act\`
 * itself reads does not make it run again. \`act\` may return a clean-up, run before the next \`act\` and when the life ends.
 */
export function life() {
  const stops = [];
  return {
    run(fn) {
      stops.push(effect(fn));
    },
    watch(read, act) {
      let last = null;
      let cleanup;
      stops.push(
        effect(function () {
          const now = read();
          if (last !== null && now.every((v, i) => Object.is(v, last[i]))) return;
          last = now;
          untracked(function () {
            if (typeof cleanup === 'function') cleanup();
            cleanup = act.apply(null, now);
          });
        })
      );
      stops.push(function () {
        if (typeof cleanup === 'function') cleanup();
      });
    },
    add(stop) {
      stops.push(stop);
    },
    destroy() {
      while (stops.length > 0) stops.pop()();
    }
  };
}

/**
 * A new element in \`parent\`: its tag, its classes, and its text when it has fixed text.
 * \`before\` places it before that node rather than at the end.
 */
export function el(parent, tag, className, text, before) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  parent.insertBefore(node, before || null);
  return node;
}

/** Keeps \`node\`'s text equal to what \`read()\` gives. */
export function bindText(l, node, read) {
  l.run(function () {
    const text = show(read());
    if (node.textContent !== text) node.textContent = text;
  });
}

/** Keeps one attribute equal to what \`read()\` gives; no value removes it. */
export function bindAttr(l, node, name, read) {
  l.run(function () {
    const value = read();
    if (value === undefined || value === null || value === false) node.removeAttribute(name);
    else node.setAttribute(name, value === true ? '' : String(value));
  });
}

/** Keeps one style property (a CSS name, such as 'color') equal to what \`read()\` gives. */
export function bindStyle(l, node, property, read) {
  l.run(function () {
    node.style.setProperty(property, show(read()));
  });
}

/**
 * A part that is on the page only while \`read()\` is true. \`build(parent, before, partLife)\` draws it before the marker
 * and returns its outer element; when the value turns false, the part's life ends and its element is removed.
 */
export function when(l, parent, read, build, before) {
  const marker = document.createComment(' shown when its condition is true ');
  parent.insertBefore(marker, before || null);
  let shown = null;
  const hide = function () {
    if (shown === null) return;
    shown.life.destroy();
    if (shown.node) shown.node.remove();
    shown = null;
  };
  l.run(function () {
    const on = truthy(read());
    if (on && shown === null) {
      const partLife = life();
      shown = { life: partLife, node: null };
      shown.node = build(parent, marker, partLife);
    } else if (!on) hide();
  });
  l.add(hide);
  return marker;
}

/**
 * Places a component with its \`mount<Name>\` function into \`parent\` (before \`before\`, when given), and ends it with the life
 * it is placed in. \`fixed\` are the inputs set once (and the callbacks it calls); \`live()\` gives the inputs that follow a
 * value, handed to the part again whenever one of them changes. A logic component draws nothing: its \`parent\` is null.
 */
export function place(l, mount, parent, fixed, live, before) {
  const part = mount(parent, Object.assign({}, fixed, live ? untracked(live) : {}), before);
  if (live) {
    l.run(function () {
      const next = live();
      untracked(function () {
        part.update(next);
      });
    });
  }
  l.add(function () {
    part.destroy();
  });
  return part;
}

/**
 * A For Each: one row per item of the list \`read()\` gives, drawn by \`mountRow(parent, item, index, before)\`, which returns
 * \`{ update(item, index), destroy() }\`. Rows are kept by their place in the list: when the list changes, the row at each
 * place is handed its new item, new places get a new row, and the rows past the end are taken off the page.
 */
export function list(l, parent, read, mountRow, before) {
  const marker = document.createComment(' a For Each: its rows are drawn before this ');
  parent.insertBefore(marker, before || null);
  const rows = [];
  l.run(function () {
    const items = read();
    untracked(function () {
      const all = Array.isArray(items) ? items : [];
      all.forEach(function (item, index) {
        if (index < rows.length) rows[index].update(item, index);
        else rows.push(mountRow(parent, item, index, marker));
      });
      while (rows.length > all.length) rows.pop().destroy();
    });
  });
  l.add(function () {
    while (rows.length > 0) rows.pop().destroy();
  });
  return marker;
}
`;

export const ROUTER_JS = `/**
 * Which page is showing. The page is named in the address after \`#\` (\`index.html#/remix\`), so the app works from any
 * folder on any static server, and a refresh stays on the page it was on.
 *
 * Generated by the export, the same in every app.
 */

let routes = [];
let startPath = '/';
let root = null;
let current = null;

/** The path the address names: \`#/remix\` is '/remix', no hash is the start page. */
export function currentPath() {
  const hash = location.hash.replace(/^#/, '');
  return hash === '' ? startPath : hash;
}

/** Shows the page at \`path\`, as a Navigate does. */
export function navigate(path) {
  if (currentPath() === path && current !== null) return;
  location.hash = path;
}

function render() {
  const path = currentPath();
  const route = routes.find(function (r) {
    return r.path === path;
  }) || routes.find(function (r) {
    return r.path === startPath;
  });
  if (current !== null) current.destroy();
  root.textContent = '';
  current = route.mount(root, {});
  if (route.title) document.title = route.title;
  window.scrollTo(0, 0);
}

/** Starts the app: the pages it has, the one it opens on, and the element they draw into. */
export function startRouter(options) {
  routes = options.routes;
  startPath = options.start;
  root = options.root;
  window.addEventListener('hashchange', render);
  render();
}
`;
