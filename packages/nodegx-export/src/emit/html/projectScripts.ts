/**
 * P134 session 12. A project's script files (`scripts/**.js`) in plain files, the React export's way (P109 ISL-005 AC7,
 * `emit/projectScriptsLib.ts`), three kinds of file earned by a Function whose Uses lists one:
 *
 * - `lib/projectScripts.js` — the loader: React's `src/lib/projectScripts.ts`, the same text with its types taken out
 *   at export time (`stripTypes` + `closeStripped`, as the client travels, `client.ts`). A file runs once, the first time
 *   anything uses it; `use()` takes any spelling of a path; a cycle sees the exports so far; a failure is remembered.
 * - `lib/projectScriptFiles.js` — the one registry, `projectScripts`, holding every file in the project, so a value a
 *   file keeps at its top level is shared by all its users, and a `use()` no text scan can see still resolves.
 * - `project-scripts/<path>.js` — each file once, the author's text verbatim inside the function the runtime compiles
 *   it as: `function (use, exports, module, Noodl, window, document)`.
 *
 * The Function's file binds `Scripts` from the registry inside its try (`functionFileJs`), so a file that fails runs none
 * of the body, as the running app fails the run.
 *
 * @module emit/html/projectScripts
 */

import type { ScriptFileIR } from '../../ir/types';
import { projectScriptsLibSource } from '../projectScriptsLib';
import { stripTypes } from '../swift/client';
import { closeStripped } from './client';

export const PROJECT_SCRIPTS_JS = 'lib/projectScripts.js';
export const PROJECT_SCRIPT_FILES_JS = 'lib/projectScriptFiles.js';

/** `engine/world.js` → `project-scripts/engine/world.js`. */
export function projectScriptFileJsPath(path: string): string {
  return `project-scripts/${path.replace(/\.js$/, '')}.js`;
}

/** The loader: React's, its types out. A line left holding `export type` would not load, and is refused by name. */
export function projectScriptsJs(): string {
  const ts = projectScriptsLibSource();
  // A lint note left above a line that was only a type notes nothing: it goes with the type.
  const js = closeStripped(ts, stripTypes(ts))
    .replace(/^[ \t]*\/\/ eslint-disable-next-line[^\n]*\n(?=[ \t]*\n)/gm, '')
    .replace(/\n{3,}/g, '\n\n');
  if (/\bexport\s+type\b|:\s*ScriptExports\b/.test(js)) throw new Error('lib/projectScripts.js still holds a type once its types are taken out');
  return `// @nodegx:generated by \`nodegx export --target html\` — src/lib/projectScripts.ts of the React export, its types taken out: the same loader.\n${js}`;
}

/** The registry: every file, by its path, under one loader. Files in path order, as the React export lists them. */
export function projectScriptFilesJs(scripts: readonly ScriptFileIR[]): string {
  const sorted = [...scripts].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const imports = sorted.map((s, i) => `import file${i} from '../${projectScriptFileJsPath(s.path)}';`);
  const rows = sorted.map((s, i) => `  ${JSON.stringify(s.path)}: file${i}`);
  return [
    '// @nodegx:generated by `nodegx export --target html` — every script file in the project, under one loader, so each',
    '// one runs once for the whole app. A Function reaches the files it lists under Uses from here (lib/projectScripts.js).',
    "import { ScriptFiles } from './projectScripts.js';",
    ...imports,
    '',
    'export const projectScripts = new ScriptFiles({',
    rows.join(',\n'),
    '});',
    ''
  ].join('\n');
}

/** One file, verbatim, inside the function the runtime compiles it as. */
export function projectScriptFileJs(script: ScriptFileIR): string {
  return [
    `// @nodegx:generated by \`nodegx export --target html\` — scripts/${script.path}, the author's code as it was written,`,
    '// inside the function the running app compiles it as. It runs once, the first time a Function uses it. Noodl, window',
    '// and document are undefined inside it, as they are in the running app: calls into the app stay in the Function.',
    'export default function (use, exports, module, Noodl, window, document) {',
    ...script.source.split(/\r\n|\n|\r/),
    '}',
    ''
  ].join('\n');
}

/** The three kinds of file, by output path: the loader, the registry, every script file in the project. */
export function projectScriptsFiles(scripts: readonly ScriptFileIR[]): Record<string, string> {
  const out: Record<string, string> = { [PROJECT_SCRIPTS_JS]: projectScriptsJs(), [PROJECT_SCRIPT_FILES_JS]: projectScriptFilesJs(scripts) };
  for (const s of scripts) out[projectScriptFileJsPath(s.path)] = projectScriptFileJs(s);
  return out;
}
