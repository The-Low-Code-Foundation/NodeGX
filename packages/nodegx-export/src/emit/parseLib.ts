    "    // RDF puts <item> as a SIBLING of <channel>, not inside it.",
    "    rawItems = many(rdf, 'item');",
    "  } else if (isObject(rss)) {",
    "    kind = 'rss';",
    "    channel = (one(rss, 'channel') as Node) || {};",
    "    rawItems = many(channel, 'item');",
    "  } else if (isObject(atom)) {",
    "    kind = 'atom';",
    "    channel = atom;",
    "    rawItems = many(atom, 'entry');",
