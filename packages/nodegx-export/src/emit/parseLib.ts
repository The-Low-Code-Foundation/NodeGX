    "function parseFeedText(document: unknown, maxBytes: number): FeedParseResult {",
    "  const parsed = parseXMLText(document, { attributePrefix: '@', alwaysArray: FEED_ARRAY_TAGS, trimValues: true, maxBytes });",
    "  if (parsed.error) return { error: parsed.error };",
