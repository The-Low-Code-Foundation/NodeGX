/**
 * The selector a `util-call` into this module carries: its trailing literal argument. `undefined` for a
 * call that is not a parse helper, or whose last argument is not a string literal — neither can be built by
 * the planner, so a lookup that answers `undefined` is a programming error upstream, not an authored shape.
 */
export function parseSelectorOf(expr: { fn: string; args: ReadonlyArray<{ kind: string; value?: unknown }> }): string | undefined {
  if (!isParseHelper(expr.fn)) return undefined;
  const last = expr.args[expr.args.length - 1];
  return last !== undefined && last.kind === 'literal' && typeof last.value === 'string' ? last.value : undefined;
}

/** `exprTsType` for a parse call — `unknown` for a selector the table does not know, never a throw. */
export function parseOutputTsType(fn: ParseHelper, selector: string | undefined): string {
  return (selector !== undefined && PARSE_OUTPUTS[fn][selector]?.tsType) || 'unknown';
}

/** `maybeUndefinedExpr` for a parse call — `true` for a selector the table does not know: the guarded answer. */
export function parseOutputMayBeUndefined(fn: ParseHelper, selector: string | undefined): boolean {
  return selector === undefined ? true : (PARSE_OUTPUTS[fn][selector]?.maybeUndefined ?? true);
}

