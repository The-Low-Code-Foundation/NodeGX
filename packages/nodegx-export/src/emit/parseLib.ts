/**
 * `src/lib/parse.ts` — `Parse CSV`, `To CSV`, `Parse XML` and `Parse Feed`, emitted into the app (EXP-011 §75).
 *
 * The same shape as {@link ./utilLib.ts}: constant text, shipped only where a component calls into it, and a
 * **separate** module from `util.ts` on that file's own rule (a project that formats a string should not ship
 * a CSV tokeniser, and an XML parser even less). The four are `util-call`s in the plan — each node is a
 * function of its inputs and holds nothing else — with one difference from the three small utilities:
 * every one of them has SEVERAL value outputs, so the call carries the output port's name as its trailing
 * literal argument (`DATE_NODES`' selector, one family over) and the helper answers that port. A one-entry
 * memo inside each helper keeps a page that reads three outputs of one node to one parse.
 *
 * A transcription of three runtime modules and four node files:
 *
 * - `noodl-runtime/src/csv.ts` — `stripBOM`, the contiguity-checking `tokenise`, `parseCSV` (the
 *   unterminated-quote sentence verbatim), `rowsToRecords`, `unionOfKeys`, `quoteCell`, `toCSV`, `rowsToCSV`.
 * - `data/parsecsv.ts` / `data/tocsv.ts` — the abstain (`textSupplied` / `itemsSupplied`: nothing arrived ⇒
 *   no Items, Count 0, no Error — Failure Contract §2), the setters' fallbacks (`delimiter || ','`,
 *   `!!hasHeader`, a `stringlist` Columns split on commas and trimmed), rows-of-cells written cell for cell.
 * - `noodl-runtime/src/xml.ts` — `scanForHostileConstructs` (the two refusals, sentences verbatim) and
 *   `parseXML` over **`fast-xml-parser` at the interpreter's own pin, 4.5.7**, with the interpreter's own
 *   options. 🔴 The one third-party dependency an emitted lib has ever declared: FED-001 R1 took the library
 *   over a hand-rolled scanner for the runtime (entity expansion is a denial-of-service hole, not a wrong
 *   answer), and a transcription of an XML parser would be a second parser that drifts — so
 *   {@link PARSE_DEPENDENCIES} is added to the exported `package.json` exactly when a component calls
 *   `parseXml` or `parseFeed`.
 * - `noodl-runtime/src/feed.ts` — the whole module: RSS/Atom/RDF detection (RDF first, its `<item>` a
 *   SIBLING of `<channel>`), the readers, `toISODate`'s retry, the Atom link family, images, enclosures,
 *   tags, authors, the identity ladder and FNV-1a `hashId`. 🔴 **The ladder's separator is a NUL byte.**
 *   `feed.ts:365` holds a literal U+0000 between the quotes, which every editor draws as a space; the
 *   transcription writes `'\u0000'` because FED-002's unique index keys on the id and a space would mint a
 *   different id for every item on the hash rung. Found by the §A differential, not by reading.
 *
 * ⚠️ **The one divergence, and where it is reported.** On a FAILED parse the interpreter keeps the previous
 * successful answer on its value outputs beside the Error (`items` is "replaced only on a successful
 * parse"); a pure call has no previous answer, so Items is absent and Count is 0 beside the Error. The
 * planner files a note at every parse node whose text arrives by wire — a literal cannot have a previous
 * parse. On a FIRST failure the two agree exactly.
 *
 * `Changed` and `Failure` are recomputation pulses and defer with the date family's sentence
 * ({@link PARSE_SIGNAL_SENTENCES}); a wire off one is not a chain the export can hang anything on.
 */

/** Where the module lands in the exported app. */
export const PARSE_LIB_PATH = 'src/lib/parse.ts';

/** The exported helpers, one per node. Sorted — the import list is sorted too. */
export const PARSE_HELPERS = ['parseCsv', 'parseFeed', 'parseXml', 'toCsv'] as const;

export type ParseHelper = (typeof PARSE_HELPERS)[number];

export function isParseHelper(fn: string): fn is ParseHelper {
  return (PARSE_HELPERS as readonly string[]).includes(fn);
}

