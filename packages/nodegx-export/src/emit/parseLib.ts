    "  return {",
    "    id,",
    "    title,",
    "    link,",
    "    published,",
    "    updated,",
    "    author: itemAuthor(raw),",
    "    summary,",
    "    content,",
    "    image: itemImage(raw),",
    "    enclosure: itemEnclosure(raw),",
    "    tags: itemTags(raw),",
    "    raw",
    "  };",
