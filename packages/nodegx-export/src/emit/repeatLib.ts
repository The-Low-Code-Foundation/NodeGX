    '  const beatRef = useRef<RepeatBeat | null>(null);',
    '  const handleRef = useRef<RepeatHandle | null>(null);',
    '  if (beatRef.current === null || handleRef.current === null) {',
    '    const created = createRepeatBeat(source, clock, () => publish());',
    '    beatRef.current = created;',
    '    handleRef.current = {',
    '      start: () => created.start(),',
    '      stop: () => created.stop(),',
    '      get count() {',
    '        return created.count;',
    '      }',
    '    };',
    '  }',
    '  const beat = beatRef.current;',
    '  // The setter runs on every render that delivers a value; an undefined option ran no setter.',
    '  if (options.interval !== undefined) beat.setIntervalInput(options.interval);',
    '  beat.setListeners(on);',
    '',
    '  useEffect(() => {',
    '    return () => {',
    '      beat.dispose();',
    '    };',
    '    // eslint-disable-next-line react-hooks/exhaustive-deps -- the beat is created once',
    '  }, []);',
    '',
    '  return handleRef.current;',
    '}'
