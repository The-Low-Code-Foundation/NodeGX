    '        return;',
    '      }',
    '',
    '      s.running = true;',
    '      s.beat = s.interval;',
    '      s.nextAt = s.clock.now() + s.beat;',
    '      if (s.count !== 0) {',
    '        s.count = 0;',
    '        s.rerender();',
    '      }',
    '      schedule(s, s.beat);',
    '      reportOutcome(s, \'done\');',
    '    },',
    '    stop() {',
    '      if (!s.running) {',
    '        reportOutcome(s, \'unchanged\');',
    '        return;',
    '      }',
    '      s.running = false;',
    '      cancel(s);',
    '      reportOutcome(s, \'done\');',
    '    },',
    '    dispose() {',
    '      s.running = false;',
    '      cancel(s);',
    '    }',
    '  };',
    '}',
    '',
    '/**',
    ' * useRepeat: one beat per mount. The Interval and the listeners are re-read every render; the effect\'s cleanup is the',
