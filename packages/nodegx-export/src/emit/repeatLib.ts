    '// outcome trio are the listeners, Count is a live getter on the handle. The Interval is the one option, read at Start',
    '// and again at every tick, so a change takes effect from the next tick. Unmounting stops the beat: the node\'s delete',
    '// listener, which the runtime runs on delete, on unmount and on leaving the page.',
