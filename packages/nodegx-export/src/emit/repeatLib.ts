    '        reportOutcome(s, \'unchanged\');',
    '        return;',
    '      }',
    '      if (!isUsableInterval(s.interval)) {',
    '        reportOutcome(s, \'failure\', {',
    '          code: REPEAT_ERROR_INTERVAL_NOT_POSITIVE,',
    '          message: `Interval is ${String(s.interval)}, and Repeat needs a number of milliseconds above zero`',
