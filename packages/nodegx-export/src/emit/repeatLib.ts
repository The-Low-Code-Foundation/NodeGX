    'import { raiseAppError } from \'./errors\';',
    '',
    '/** The failure a Start reports when its Interval is not a number of milliseconds above zero. */',
    'export const REPEAT_ERROR_INTERVAL_NOT_POSITIVE = \'repeat/interval-not-positive\';',
    '',
    '/** Where the node sits: the provenance a raise carries. */',
    'export interface RepeatSource {',
    '  /** The authored label, or the node\'s display name. */',
    '  label: string;',
    '  /** The node\'s graph id. */',
    '  nodeId: string;',
    '  /** The component it sits in, \'/Pages/Home\'. */',
    '  componentName: string;',
    '}',
    '',
    '/** The node\'s one value input. Undefined means no setter ran, and the Interval keeps its last value. */',
    'export interface RepeatOptions {',
    '  interval?: unknown;',
    '}',
    '',
    '/** The signal outputs, in the node\'s declaration order. */',
    'export interface RepeatListeners {',
    '  tick?: () => void;',
    '  done?: () => void;',
    '  completed?: () => void;',
    '  unchanged?: () => void;',
    '  failure?: () => void;',
    '}',
    '',
    'export interface RepeatHandle {',
    '  /** The Start action: Done when a beat began, Unchanged while one runs, Failure on an unusable Interval. */',
    '  start(): void;',
    '  /** The Stop action: Done when a beat was stopped, Unchanged when none ran. */',
    '  stop(): void;',
    '  /** How many times Tick has fired since the last Start. Start resets it; Stop keeps it. */',
    '  readonly count: number;',
    '}',
    '',
    '/** The clock the beat runs on. The browser\'s by default; a test hands its own. */',
    'export interface RepeatClock {',
    '  now(): number;',
    '  setTimeout(fn: () => void, ms: number): unknown;',
    '  clearTimeout(handle: unknown): void;',
    '}',
    '',
    'const browserClock: RepeatClock = {',
    '  now: () => (typeof performance !== \'undefined\' ? performance.now() : Date.now()),',
    '  setTimeout: (fn, ms) => setTimeout(fn, ms),',
    '  clearTimeout: (handle) => clearTimeout(handle as ReturnType<typeof setTimeout>)',
    '};',
    '',
    '/** isUsableInterval: a finite number of milliseconds above zero. */',
    'export function isUsableInterval(value: unknown): value is number {',
    '  return typeof value === \'number\' && Number.isFinite(value) && value > 0;',
    '}',
    '',
    '/** One node\'s beat, outside React: the node\'s `_internal` and its three handlers. The hook below hosts one. */',
    'export interface RepeatBeat {',
    '  readonly count: number;',
    '  readonly running: boolean;',
    '  /** The Interval input\'s setter: stores what arrived. Read at Start and at every tick. */',
    '  setIntervalInput(value: unknown): void;',
    '  setListeners(on: RepeatListeners): void;',
    '  start(): void;',
    '  stop(): void;',
    '  /** The delete listener: the beat stops, and no outcome fires. */',
    '  dispose(): void;',
    '}',
    '',
    'interface RepeatState {',
    '  source: RepeatSource;',
    '  clock: RepeatClock;',
    '  rerender: () => void;',
    '  listeners: RepeatListeners;',
    '  running: boolean;',
    '  count: number;',
    '  /** The Interval input as last set, in milliseconds. */',
    '  interval: unknown;',
    '  /** The interval the running beat uses: the last valid one. */',
    '  beat: number;',
    '  /** The time the next tick is due. */',
    '  nextAt: number;',
    '  /** The one pending timeout. Scheduling again replaces it, as the scheduler keeps one timer per node. */',
    '  timer: unknown;',
    '}',
    '',
    'function reportOutcome(s: RepeatState, outcome: \'done\' | \'unchanged\' | \'failure\', failure?: { code: string; message: string }): void {',
    '  if (outcome === \'failure\' && failure !== undefined) {',
    '    raiseAppError({ code: failure.code, message: failure.message, nodeId: s.source.nodeId, nodeType: \'Repeat\', componentName: s.source.componentName });',
    '  }',
    '  s.listeners[outcome]?.();',
    '  s.listeners.completed?.();',
    '}',
    '',
    'function cancel(s: RepeatState): void {',
    '  if (s.timer !== null) {',
    '    s.clock.clearTimeout(s.timer);',
    '    s.timer = null;',
    '  }',
    '}',
    '',
    'function schedule(s: RepeatState, ms: number): void {',
    '  cancel(s);',
    '  s.timer = s.clock.setTimeout(() => {',
    '    s.timer = null;',
    '    tick(s);',
    '  }, ms);',
    '}',
    '',
    '/** _tick: Count, then Tick, then the next tick on the beat. */',
    'function tick(s: RepeatState): void {',
    '  if (!s.running) return;',
    '',
    '  s.count += 1;',
    '  s.rerender();',
    '  s.listeners.tick?.();',
    '',
    '  // A Stop wired from Tick has already run by here.',
    '  if (!s.running) return;',
    '',
    '  if (isUsableInterval(s.interval)) s.beat = s.interval;',
    '  const now = s.clock.now();',
    '  s.nextAt += s.beat;',
    '  if (s.nextAt <= now) {',
    '    // Ticks missed while the tab was throttled are skipped, not replayed, and the beat keeps its phase.',
    '    s.nextAt += Math.ceil((now - s.nextAt) / s.beat + Number.EPSILON) * s.beat;',
    '  }',
    '  schedule(s, s.nextAt - now);',
    '}',
