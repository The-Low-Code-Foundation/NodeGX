    '    source,',
    '    clock,',
    '    rerender,',
    '    listeners: {},',
    '    running: false,',
    '    count: 0,',
    '    interval: 1000,',
    '    beat: 1000,',
    '    nextAt: 0,',
    '    timer: null',
    '  };',
    '  return {',
    '    get count() {',
    '      return s.count;',
    '    },',
    '    get running() {',
    '      return s.running;',
    '    },',
    '    setIntervalInput(value: unknown) {',
    '      s.interval = value;',
    '    },',
    '    setListeners(on: RepeatListeners) {',
    '      s.listeners = on;',
    '    },',
