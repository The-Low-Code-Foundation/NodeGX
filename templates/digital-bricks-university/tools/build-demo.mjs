#!/usr/bin/env node
/**
 * THE BROWSER-ONLY DEMO, DERIVED FROM THE TEMPLATE (DBU-11).
 *
 *   node tools/build-demo.mjs [--out <dir>]     writes ../demo/ (beside app/, gitignored)
 *
 * The demo is this project with its backend replaced by a service worker that plays it in the visitor's
 * browser (OpenNoodl TPL-008's ruling R9: "a browser-only demo mode, not a public backend"). DERIVED, NEVER
 * WRITTEN TWICE: the page graphs are the template's, byte for byte, and the backend is the template's own
 * cloud functions, run by tools/demo/engine.js against the world tools/lib/world.mjs builds from
 * backend/fixtures. tools/check-demo.mjs fails on any difference not in this list:
 *
 *   - nodegx.project.json: the demo's own name and id; `headCode` loads demo/boot.js; HASH navigation
 *     (nodegx.io serves template folders with a plain file server and no fallback, so a reload of
 *     /templates/<x>/coach/inbox would be a 404); the backend endpoint is `demo-api`, a path under the
 *     demo's own folder that only the service worker answers.
 *   - components/__cloud__/ is not copied (it is inside demo-sw.js), and the registry loses its rows.
 *   - added: demo-sw.js (engine + the functions + the policy + the world builder + the fixtures),
 *     demo/boot.js, demo/files/ (the fixture files the world uploads), docs/START-HERE.md.
 *   - not copied: tools/, backend/, docs/ (but START-HERE), hosting/, privacy/, nodegx.security.json, nodegx.automations.json,
 *     .mcp.json, .previews/.
 *
 * The persona switcher and the intro are the template's own Demo/ components: they show only when
 * window.dbuDemo exists, which only demo/boot.js creates.
 *
 * Written at indent 2, as the project's files are.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { APP, arg, readJson } from './lib/local.mjs';
import { cloudGraphs, unsupportedNodes } from './lib/demo.mjs';
import { FILES_DIR, worldSources } from './lib/seed.mjs';

export const OUT = arg('out') || join(APP, '..', 'demo');
export const ENDPOINT = 'demo-api';
export const DEMO_NAME = 'Digital Bricks University (demo)';
export const DEMO_ID = '7b0c5d1e-dbu1-4d3e-9a11-de0000000011';
/** Paths under app/ the demo carries over unchanged (files, or folders copied whole). */
export const COPIED = ['nodegx.styles.json', 'noodl_modules', 'AGENTS.md'];
/** Paths under app/ the demo leaves out, besides components/__cloud__. */
export const LEFT_OUT = ['tools', 'backend', 'docs', 'hosting', 'privacy', 'nodegx.security.json', 'nodegx.automations.json', '.mcp.json', '.previews', '.gitignore', 'CLAUDE.md'];

const json = (v) => JSON.stringify(v, null, 2);

/** The demo's nodegx.project.json: the template's, with the four named changes. */
export function demoProject() {
  const p = readJson('nodegx.project.json');
  p.name = DEMO_NAME;
  p.id = DEMO_ID;
  p.settings = { ...p.settings, navigationPathType: 'hash', headCode: '<script src="demo/boot.js"></script>' };
  p.metadata = { ...p.metadata, cloudservices: { ...p.metadata.cloudservices, endpoint: ENDPOINT } };
  return p;
}

/** The registry without the cloud functions, its totals recounted. */
export function demoRegistry() {
  const r = readJson('components', '_registry.json');
  const components = Object.fromEntries(Object.entries(r.components).filter(([k]) => !k.startsWith('__cloud__')));
  const vals = Object.values(components);
  return {
    ...r,
    components,
    stats: {
      totalComponents: vals.length,
      totalNodes: vals.reduce((a, c) => a + (c.nodeCount || 0), 0),
      totalConnections: vals.reduce((a, c) => a + (c.connectionCount || 0), 0)
    }
  };
}

/** world.mjs as a script: the same source, its `export`s dropped. */
function worldSource() {
  const src = readFileSync(join(APP, 'tools', 'lib', 'world.mjs'), 'utf8');
  if (/^\s*import\s/m.test(src)) throw new Error('build-demo: world.mjs must not import anything');
  return src.replace(/^export (const|function) /gm, '$1 ');
}

/** demo-sw.js: what the service worker runs. */
export function serviceWorker() {
  const graphs = cloudGraphs();
  const bad = unsupportedNodes(graphs);
  if (bad.length) throw new Error(`build-demo: the demo engine does not know these cloud nodes:\n  ${bad.join('\n  ')}`);
  const { appId, type } = readJson('nodegx.project.json').metadata.cloudservices;
  const data = { graphs, policy: readJson('nodegx.security.json'), sources: worldSources(), cloudservices: { appId, type } };
  return [
    '/* GENERATED by tools/build-demo.mjs (DBU-11), do not edit: change the template and rebuild. */',
    `var DBU_DEMO = ${JSON.stringify(data)};`,
    '(function () {',
    worldSource(),
    'DBU_DEMO.buildWorld = buildWorld;',
    'DBU_DEMO.resolveRows = resolveRows;',
    '})();',
    readFileSync(join(APP, 'tools', 'demo', 'engine.js'), 'utf8'),
    readFileSync(join(APP, 'tools', 'demo', 'sw.js'), 'utf8')
  ].join('\n');
}

export function bootScript() {
  const { appId, type } = readJson('nodegx.project.json').metadata.cloudservices;
  return readFileSync(join(APP, 'tools', 'demo', 'boot.js'), 'utf8').replace('__APP_ID__', appId).replace('__TYPE__', type);
}

export const START_HERE = `# Digital Bricks University: demo

The **Digital Bricks University** template with its backend played by your own browser, so it runs on a web
page with no server and no account. Look as Camille (a learner) or as Richard (her coach), hand in, review,
message, plan: everything works, and nothing leaves the browser.

**Generated, do not edit.** \`node tools/build-demo.mjs\` in the template writes it, and
\`node tools/check-demo.mjs\` fails on any difference the generator did not make.

## What is different from the template

- **A service worker is the backend** (\`demo-sw.js\`). It answers every request under \`demo-api/\` by running
  the template's own cloud functions against an example world kept in this browser (IndexedDB), built from the
  template's fixtures on the first visit, with its dates around today.
- **No sign-in.** The first page offers two people to look as; the strip at the top switches between them,
  and **Reset demo** puts the example world back.
- **No email.** What the app would have mailed is kept, unsent, inside the demo's store.
- **Hash URLs** (\`#/coach/inbox\`), so a reload works on a static host.

To run it for real, with a backend, magic-link sign-in and email, start from the template and read its
\`docs/START-HERE.md\`.
`;

export function build(out = OUT) {
  if (existsSync(out)) rmSync(out, { recursive: true });
  mkdirSync(out, { recursive: true });
  const write = (rel, content) => {
    const p = join(out, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  };
  write('nodegx.project.json', json(demoProject()));
  for (const rel of COPIED) cpSync(join(APP, rel), join(out, rel), { recursive: true });
  const comps = join(APP, 'components');
  for (const e of readdirSync(comps, { withFileTypes: true })) {
    if (e.name === '__cloud__' || e.name === '_registry.json') continue;
    cpSync(join(comps, e.name), join(out, 'components', e.name), { recursive: true });
  }
  write('components/_registry.json', json(demoRegistry()));
  write('demo-sw.js', serviceWorker());
  write('demo/boot.js', bootScript());
  cpSync(FILES_DIR, join(out, 'demo', 'files'), { recursive: true });
  write('docs/START-HERE.md', START_HERE);
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = build();
  const size = readFileSync(join(out, 'demo-sw.js')).length;
  console.log(`build-demo: wrote ${out} (demo-sw.js ${(size / 1024).toFixed(0)} KB)`);
}
