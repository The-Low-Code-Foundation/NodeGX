#!/usr/bin/env node
/**
 * WHAT A PRODUCTION BACKEND STARTS WITH (TASK-L183 §1).
 *
 * Writes `backend/production.json`: `{ rows: { Concept: [{ conceptId, title }] } }`
 * and NOTHING about any person. The demo world (`seed.json`) is invented people;
 * a real client's backend must never hold one of them, and check-production.mjs
 * fails if it does.
 *
 * ── WHERE THE TITLES COME FROM, AND A DEVIATION FROM THE TASK DOC ─────────
 * §1 says "generated from the same source build-seed reads them from". That
 * source is the FIXTURES, which name only the 20 concepts Sam's world happens to
 * touch; a coach building a real learner's path needs the whole corpus. So the
 * titles come from the PRODUCT's own corpus (`src/lib/domain/loom/concepts`),
 * compiled in memory the way check-dossier.mjs compiles the product, and the
 * property §1 was after is asserted instead of assumed: every Concept the seed
 * holds must carry exactly the corpus's title for its id, or this fails by name.
 * A title cannot differ between the demo and production.
 *
 * Deterministic: corpus order, no timestamps. Running it twice writes a
 * byte-identical file.
 *
 * Run: node tools/build-production.mjs          (DBT_REPO=<product checkout> if not a sibling)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const TEMPLATE = join(here, '..');
const DBT_REPO = process.env.DBT_REPO || resolve(here, '..', '..', '..', '..', 'digital-bricks-training');
const CORPUS = join(DBT_REPO, 'src', 'lib', 'domain', 'loom', 'concepts', 'index.ts');

if (!existsSync(CORPUS)) {
  console.error(`build-production: the product's corpus is not at ${CORPUS} — set DBT_REPO. Refusing to write an empty corpus.`);
  process.exit(2);
}

const bundled = await build({
  stdin: { contents: `export { allConcepts } from ${JSON.stringify(CORPUS)};`, resolveDir: DBT_REPO, loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'silent'
});
const url = 'data:text/javascript;base64,' + Buffer.from(bundled.outputFiles[0].text).toString('base64');
const { allConcepts } = await import(url);

const failures = [];
const concepts = allConcepts.map((c) => ({ conceptId: c.id, title: c.title }));
const titleOf = new Map(concepts.map((c) => [c.conceptId, c.title]));
if (titleOf.size !== concepts.length) failures.push('the corpus names one concept id twice');

// The property §1 wanted: the demo and production cannot disagree about a title.
const seed = JSON.parse(readFileSync(join(TEMPLATE, 'backend', 'seed.json'), 'utf8'));
for (const row of seed.rows.Concept || []) {
  if (!titleOf.has(row.conceptId)) failures.push(`seed Concept '${row.conceptId}' is not in the product's corpus`);
  else if (titleOf.get(row.conceptId) !== row.title) {
    failures.push(`seed Concept '${row.conceptId}' is titled "${row.title}"; the corpus says "${titleOf.get(row.conceptId)}"`);
  }
}

if (failures.length) {
  console.error('build-production: FAILED —\n  ' + failures.join('\n  '));
  process.exit(1);
}

const out = {
  _about:
    'GENERATED by tools/build-production.mjs from the product corpus — never edit. What a production backend starts with: ' +
    'the concept titles and nothing about any person (TASK-L183).',
  rows: { Concept: concepts }
};
writeFileSync(join(TEMPLATE, 'backend', 'production.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`build-production: ${concepts.length} concepts; every one of the seed's ${(seed.rows.Concept || []).length} titles agrees with the corpus.`);
