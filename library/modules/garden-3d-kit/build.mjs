#!/usr/bin/env node
/**
 * Build `project/noodl_modules/garden-3d-kit/index.js` = a banner + `src/kit3d.js` verbatim.
 *
 *     node library/modules/garden-3d-kit/build.mjs
 *
 * The same shape as garden-kit's build: nothing is bundled INTO this file. three.js is vendored BESIDE it
 * (`three.min.js`, listed in manifest.json `dependencies`, so the page loads it before index.js and the node reads
 * the `THREE` global). Deterministic: the same input gives the same bytes, so `git diff` on the output is a real diff.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'garden-3d-kit', 'index.js');

const kit = readFileSync(join(here, 'src', 'kit3d.js'), 'utf8');

const banner =
  '/* garden-3d-kit — a NodeGX node kit. GENERATED by build.mjs: this banner, then src/kit3d.js verbatim.\n' +
  '   Nothing is bundled above it: three.js is vendored beside this file as three.min.js and loaded first by the\n' +
  '   manifest (see README.md). Edit src/kit3d.js, not this file. */\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + kit);
console.log(`wrote ${out} (${(kit.length / 1024).toFixed(0)} KB kit)`);
