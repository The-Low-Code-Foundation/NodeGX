#!/usr/bin/env node
/**
 * Build `project/noodl_modules/three-kit/index.js` = a banner + `src/kit.js` verbatim.
 *
 *     node library/modules/three-kit/build.mjs
 *
 * The same shape as garden-3d-kit's build: nothing is bundled INTO this file. three.js is vendored BESIDE it
 * (`three.min.js`, listed in manifest.json `dependencies`, so the page loads it before index.js and the nodes read the
 * `THREE` global). Deterministic: the same input gives the same bytes.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'three-kit', 'index.js');
const kit = readFileSync(join(here, 'src', 'kit.js'), 'utf8');
const banner =
  '/* three-kit — three.js as NodeGX nodes (a prototype). GENERATED by build.mjs: this banner, then src/kit.js verbatim.\n' +
  '   three.js is vendored beside this file as three.min.js and loaded first by the manifest. Edit src/kit.js, not this file. */\n';
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + kit);
console.log(`wrote ${out} (${(kit.length / 1024).toFixed(0)} KB kit)`);
