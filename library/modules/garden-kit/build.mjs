#!/usr/bin/env node
/**
 * Build `project/noodl_modules/garden-kit/index.js` = a banner + `src/kit.js` verbatim.
 *
 *     node library/modules/garden-kit/build.mjs
 *
 * The same shape as game-kit's build without the avatar bundle: this kit vendors nothing. Every sprite is inline
 * SVG in the source, so the file a project installs is the file a person edits, under one banner. Deterministic:
 * the same input gives the same bytes, so `git diff` on the output is a real diff.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'garden-kit', 'index.js');

const kit = readFileSync(join(here, 'src', 'kit.js'), 'utf8');

const banner =
  '/* garden-kit — a NodeGX node kit. GENERATED by build.mjs: this banner, then src/kit.js verbatim.\n' +
  '   Nothing is bundled above it: every sprite is inline SVG in the source (see README.md).\n' +
  '   Edit src/kit.js, not this file. */\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + kit);
console.log(`wrote ${out} (${(kit.length / 1024).toFixed(0)} KB kit)`);
