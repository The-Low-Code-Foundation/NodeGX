#!/usr/bin/env node
/**
 * Build `project/noodl_modules/garden-kit/index.js` = a banner + `src/blocks.js` + `src/kit.js`, each verbatim.
 *
 *     node library/modules/garden-kit/build.mjs
 *
 * The same shape as game-kit's build without the avatar bundle. Every sprite is inline SVG in the source, so the file
 * a project installs is the files a person edits, under one banner. P108 IW-004: `blocks.js` (the Blocks node, on
 * Blockly) comes first and `kit.js` registers what it returns; Blockly 12.3.1 is vendored BESIDE index.js
 * (`blockly_compressed.js` and its messages, manifest `dependencies`), never bundled into it. Deterministic: the same
 * input gives the same bytes, so `git diff` on the output is a real diff.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'garden-kit', 'index.js');

const blocks = readFileSync(join(here, 'src', 'blocks.js'), 'utf8');
const kit = readFileSync(join(here, 'src', 'kit.js'), 'utf8');

const banner =
  '/* garden-kit — a NodeGX node kit. GENERATED by build.mjs: this banner, then src/blocks.js and src/kit.js verbatim.\n' +
  '   Nothing is bundled above them: every sprite is inline SVG in the source; Blockly is vendored beside this file\n' +
  '   and loaded first by the manifest (see README.md). Edit src/, not this file. */\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + blocks + kit);
console.log(`wrote ${out} (${(blocks.length / 1024).toFixed(0)} KB blocks + ${(kit.length / 1024).toFixed(0)} KB kit)`);
