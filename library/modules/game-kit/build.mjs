#!/usr/bin/env node
/**
 * Build `project/noodl_modules/game-kit/index.js` = the DiceBear avatar bundle
 * (esbuild, minified, one global `NodegxDicebear`) + `src/kit.js` verbatim.
 *
 *     node library/modules/game-kit/build.mjs
 *
 * Deterministic: the same inputs give the same bytes, so `git diff` on the
 * output is a real diff. Run it twice and compare if in doubt.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'game-kit', 'index.js');

const bundle = await build({
  entryPoints: [join(here, 'src', 'avatars-entry.js')],
  bundle: true,
  format: 'iife',
  globalName: 'NodegxDicebear',
  minify: true,
  write: false,
  logLevel: 'warning',
  legalComments: 'none'
});
const avatars = bundle.outputFiles[0].text;
const kit = readFileSync(join(here, 'src', 'kit.js'), 'utf8');

const banner =
  '/* game-kit — a NodeGX node kit. GENERATED by build.mjs: the first line is the DiceBear avatar\n' +
  '   bundle (MIT core; see README.md for each collection\'s licence), the rest is src/kit.js verbatim.\n' +
  '   Edit src/kit.js, not this file. */\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + avatars + '\n' + kit);
console.log(`wrote ${out} (${(avatars.length / 1024).toFixed(0)} KB avatars + ${(kit.length / 1024).toFixed(0)} KB kit)`);
