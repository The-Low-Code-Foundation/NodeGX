#!/usr/bin/env node
/**
 * Build `project/noodl_modules/nightbook-kit/` from `src/`:
 *
 *   index.js       = banner + src/kit.js verbatim (no bundler: the kit is plain JS the browser runs as-is)
 *   manifest.json  = written here, so `main` cannot drift
 *   README.md      = src/README.md verbatim
 *
 * and `project/noodl_modules/nightbook-fonts/` from `fonts/`: the six display faces as woff2 with their
 * licences, and a stylesheet the manifest names, so a page renders them with no network (DESK-7).
 *
 *     node library/modules/nightbook-kit/build.mjs
 *
 * Template-private (TPL-011, the evening journal): there is no `library.json`, so it is not a card
 * on the shelf. The journal's template installs it from `project/noodl_modules/` before authoring,
 * the way TPL-007 installs game-kit. Deterministic: the same inputs give the same bytes.
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'project', 'noodl_modules', 'nightbook-kit');

const kit = readFileSync(join(here, 'src', 'kit.js'), 'utf8');
const banner =
  '/* nightbook-kit — the page a child decorates (TPL-011). GENERATED by library/modules/nightbook-kit/build.mjs\n' +
  '   from src/kit.js, verbatim below this comment. Edit src/kit.js, not this file. React is the runtime\'s global. */\n';

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'index.js'), banner + kit);
copyFileSync(join(here, 'src', 'README.md'), join(out, 'README.md'));
writeFileSync(
  join(out, 'manifest.json'),
  JSON.stringify({ name: 'Nightbook kit', main: 'index.js', dependencies: [], nodeKitTypes: '1.0.0' }, null, 2) + '\n'
);
const fontsOut = join(here, 'project', 'noodl_modules', 'nightbook-fonts');
rmSync(fontsOut, { recursive: true, force: true });
mkdirSync(fontsOut, { recursive: true });
const fontFiles = readdirSync(join(here, 'fonts')).sort();
for (const f of fontFiles) copyFileSync(join(here, 'fonts', f), join(fontsOut, f));
writeFileSync(
  join(fontsOut, 'manifest.json'),
  JSON.stringify(
    {
      name: 'Nightbook fonts',
      browser: { stylesheets: ['noodl_modules/nightbook-fonts/styles.css'] },
      _note: 'TPL-011: Chewy, Caveat, Bungee, Pacifico, Cherry Bomb One and Rubik Doodle Shadow, bundled so a child\'s page renders offline. GENERATED by library/modules/nightbook-kit/build.mjs from fonts/.'
    },
    null,
    2
  ) + '\n'
);
console.log(`wrote ${fontsOut} (${fontFiles.filter((f) => f.endsWith('.woff2')).length} faces)`);
console.log(`wrote ${out}/index.js (${(kit.length / 1024).toFixed(0)} KB)`);
