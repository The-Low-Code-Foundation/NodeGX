#!/usr/bin/env node
/**
 * The "How export works" page (`docs-site/docs/how-export-works.md`), generated.
 *
 * The worked example is not written by hand: `sample/` is a NodeGX project (a page with a count, two buttons, a
 * Counter and a String Format), exported here with `@nodegx/export` bundled from its source, and the page shows the
 * graph beside the files the exporter wrote. The node-by-node table is the export ledger
 * (`packages/nodegx-export/coverage-ledger.json`), with each node linked to its page in the node reference.
 *
 * The exporter is bundled from the working tree with esbuild, as its own build does, so a stale `dist/` cannot
 * answer. An uncommitted exporter edit by another session would therefore show here: run `--check` against a clean
 * exporter before committing a regenerated page.
 *
 *   node scripts/export-doc/build.js           write the page
 *   node scripts/export-doc/build.js --check   fail if the committed page is stale
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const { slugify, escapeAngles } = require('../generate-node-docs');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'docs-site/docs/how-export-works.md');
const SAMPLE = path.join(__dirname, 'sample');
const EXPORT_PKG = path.join(ROOT, 'packages/nodegx-export');
const CATALOG = path.join(ROOT, 'packages/noodl-types/src/node-catalog.json');
const ENRICHED = path.join(ROOT, 'packages/noodl-types/src/node-catalog-enriched.json');
const LEDGER = path.join(EXPORT_PKG, 'coverage-ledger.json');

const { BECAME } = require('./example');

const SHOWN_FILES = ['src/pages/Home.tsx', 'src/pages/Home.module.css', 'src/App.tsx'];

function exportSample() {
  const esbuild = require(require.resolve('esbuild', { paths: [EXPORT_PKG] }));
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'export-doc-'));
  try {
    const bundle = path.join(tmp, 'export.cjs');
    esbuild.buildSync({
      entryPoints: [path.join(EXPORT_PKG, 'src/index.ts')],
      bundle: true,
      platform: 'node',
      target: 'node22',
      format: 'cjs',
      outfile: bundle,
      logLevel: 'error'
    });
    const exporter = require(bundle);
    const catalog = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
    const app = exporter.emitApp(exporter.parseProject(SAMPLE, catalog), catalog);
    return app;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

function main() {
  const check = process.argv.includes('--check');
  const app = exportSample();
  const enriched = JSON.parse(fs.readFileSync(ENRICHED, 'utf8'));
  const ledger = Object.values(JSON.parse(fs.readFileSync(LEDGER, 'utf8')).entries);

  const nodes = new Map(
    enriched.nodes.map((n) => [
      n.typeName,
      {
        name: n.displayName || n.typeName,
        category: n.category || 'Uncategorised',
        deprecated: !!n.isDeprecated,
        link: `./nodes/${slugify(n.category || 'uncategorised')}/${slugify(n.typeName)}.md`
      }
    ])
  );
  const link = (typeName) => {
    const n = nodes.get(typeName);
    if (!n) throw new Error(`export-doc: node type ${typeName} is not in the catalog`);
    return `[${n.name}](${n.link})`;
  };

  const fence = (lang, text) => {
    if (text.includes('```')) throw new Error('export-doc: a code block contains a triple backtick');
    return '```' + lang + '\n' + text.replace(/\n+$/, '') + '\n```';
  };
  const readSample = (rel) => JSON.parse(fs.readFileSync(path.join(SAMPLE, rel), 'utf8'));
  const page = readSample('components/Pages/Home/nodes.json').nodes;
  const wires = readSample('components/Pages/Home/connections.json').connections;

  for (const f of SHOWN_FILES) if (!app.files[f]) throw new Error(`export-doc: the exporter wrote no ${f}`);
  const sampleTypes = new Set([...page.map((n) => n.type), 'Router']);
  for (const [t] of BECAME) if (!sampleTypes.has(t)) throw new Error(`export-doc: ${t} is described but not in the sample`);

  const counts = ledger.reduce((acc, e) => ((acc[e.status] = (acc[e.status] || 0) + 1), acc), {});
  const total = ledger.length;

  const out = [];
  out.push('---');
  out.push('title: How export works');
  out.push('sidebar_position: 4.5');
  out.push('description: How a NodeGX project becomes a React app you own, node by node, and where other frameworks stand.');
  out.push('---');
  out.push('');
  out.push('<!-- Generated by scripts/export-doc/build.js from scripts/export-doc/sample and the export ledger. Do not edit this file. -->');
  out.push('');
  out.push(
    'A NodeGX project can be exported as an ordinary React app: React 19, Vite and TypeScript, with no NodeGX runtime inside it. ' +
      'You can read it, change it, build it and host it anywhere. The editor\'s **Export React code** command and the `@nodegx/export` ' +
      'package run the same code, so what this page shows is what you get from either.'
  );
  out.push('');
  // The ledger's own headline (export-ledger:picker): the picker's front-end nodes, deprecated ones left out.
  const status = new Map(ledger.map((e) => [e.typeName, e.status]));
  const picker = enriched.nodes.filter((n) => n.inNodePicker && !n.isDeprecated);
  const front = picker.filter((n) => status.get(n.typeName) !== 'backend-only');
  const frontExported = front.filter((n) => ['translated', 'stubbed'].includes(status.get(n.typeName)));
  out.push(
    `Every front-end node you can place from the node picker today exports: ${frontExported.length} of ${front.length}. ` +
      `Across all ${total} node types in the catalog, the ones that do not are deprecated, cannot be placed, or run only on the backend. They are listed at the bottom of this page, each with the reason.`
  );
  out.push('');

  out.push('## The pipeline {#pipeline}');
  out.push('');
  out.push('The export is four pure steps over the project files. Nothing opens a window and nothing is run.');
  out.push('');
  out.push('1. **Parse.** The project folder (`nodegx.project.json` and each component\'s `nodes.json` and `connections.json`) is read into an intermediate representation: plain data, with every node keeping the id it has in the project.');
  out.push('2. **Analyse.** Each component\'s tree is walked and every node gets a decision: it renders as an element, it becomes state, it compiles away into an expression, it becomes a call to a small library, or it is refused. Signal wires become the bodies of event handlers, and value wires become reads.');
  out.push('3. **Emit.** The decisions are written out as TSX components, one CSS module per component, the app shell with its routes, and the build files.');
  out.push('4. **Report.** Everything refused is written into the app as `EXPORT-REPORT.md`, with the reason in the exporter\'s own words. The exporter never guesses: a node it has no rule for is left out and named, not translated approximately.');
  out.push('');
  out.push('The source is in `packages/nodegx-export/src`: `parse/`, `ir/`, `analyze/` and `emit/`, in that order.');
  out.push('');

  out.push('## A worked example {#example}');
  out.push('');
  out.push(
    'A page with a count and two buttons. **Add one** increases a Counter, **Reset** sets it back to zero, and a String Format turns the count into a sentence for the Text. ' +
      'Everything below is generated: this project is exported every time the page is.'
  );
  out.push('');
  out.push('### The graph');
  out.push('');
  out.push('The page\'s nodes (`components/Pages/Home/nodes.json`):');
  out.push('');
  out.push(fence('json', JSON.stringify(page, null, 2)));
  out.push('');
  out.push('And its wires (`connections.json`):');
  out.push('');
  out.push('| From | Output | To | Input |');
  out.push('|---|---|---|---|');
  const label = (id) => {
    const n = page.find((x) => x.id === id);
    return `${escapeAngles(n.label)} (${link(n.type)})`;
  };
  for (const w of wires) out.push(`| ${label(w.fromId)} | \`${w.fromProperty}\` | ${label(w.toId)} | \`${w.toProperty}\` |`);
  out.push('');
  out.push('### What the export wrote');
  out.push('');
  out.push(`${Object.keys(app.files).length} files:`);
  out.push('');
  out.push(Object.keys(app.files).map((f) => `- \`${f}\``).join('\n'));
  out.push('');
  for (const f of SHOWN_FILES) {
    const lang = f.endsWith('.css') ? 'css' : 'tsx';
    out.push(fence(`${lang} title="${f}"`, app.files[f]));
    out.push('');
  }
  out.push('### What each node became');
  out.push('');
  out.push('| Node | In the React app |');
  out.push('|---|---|');
  for (const [t, words] of BECAME) out.push(`| ${link(t)} | ${words.replace(/\|/g, '\\|')} |`);
  out.push('');
  out.push(
    'There is no NodeGX runtime in the result. The Counter is not an object with methods any more: its state is one hook and its actions are the lines that call the setter. ' +
      'String Format leaves nothing behind but the string. This is what the export aims for with every node: the code a React developer would have written.'
  );
  out.push('');
  const report = app.files['EXPORT-REPORT.md'] || '';
  const claims = report.indexOf('## What this export claims');
  if (claims < 0) throw new Error('export-doc: EXPORT-REPORT.md has no "What this export claims" section');
  const nextHeading = report.indexOf('\n## ', claims + 5);
  const section = report.slice(claims, nextHeading > 0 ? nextHeading : undefined).replace(/^## .*\n+/, '');
  const claimText = section.split(/\n### /)[0].trim();
  out.push('### What the export claims');
  out.push('');
  out.push('Every export carries its own `EXPORT-REPORT.md`. This is the part that says what the export does and does not promise, from the report written for this example. "The list above" is the report\'s list of what was refused:');
  out.push('');
  out.push(claimText.split('\n').map((l) => (l ? `> ${l}` : '>')).join('\n'));
  out.push('');

  out.push('## Data and the backend {#backend}');
  out.push('');
  out.push(
    'An app that uses records, users or cloud functions exports with a small client that talks to its NodeGX backend over the backend\'s HTTP API. ' +
      'The exported app is the front end; the backend stays where it is, and the nodes that only run inside cloud functions have no React form.'
  );
  out.push('');

  out.push('## Known limits {#limits}');
  out.push('');
  out.push('- The export reads the project files as written. The editor patches some older graphs when it opens them, and where the two disagree the export follows the file.');
  out.push('- An exported app does not yet pass `npm run build` in every case. Build it and run it before you rely on it.');
  out.push('- Nothing in the exported app is run by the exporter. The report says what was translated by rule; testing the app is yours.');
  out.push('- Export is one-way. Editing the exported code does not change your NodeGX project, and exporting again overwrites what you changed.');
  out.push('');

  out.push('## Other frameworks {#other-frameworks}');
  out.push('');
  out.push(
    '**Not built yet.** React is the only export today, and no other framework is promised. The plan is not a second generator per framework, ' +
      'which would mean a full set of per-node rules for each one, kept in step forever. It is to port the exported React app to Svelte or Vue with AI assistance, ' +
      'and to check the port by replaying the same recorded behaviour traces the React export can be checked against.'
  );
  out.push('');
  out.push(
    'What makes that plausible is that the node model does not depend on React: React is confined to how visual nodes render. ' +
      'Each node\'s behaviour is written down as an executable spec, shown on its page under **Under the hood**, and that is the reference any port has to match.'
  );
  out.push('');

  out.push('## Every node, and whether it exports {#nodes}');
  out.push('');
  out.push(
    `From the export ledger, which classifies every node type in the catalog. ${counts.translated} export to React, ${counts.deferred || 0} do not yet` +
      `${counts.stubbed ? `, ${counts.stubbed} export as a typed stub` : ''} and ${counts['backend-only'] || 0} run only on the backend.`
  );
  out.push('');
  const byStatus = (status) =>
    ledger
      .filter((e) => e.status === status)
      .map((e) => ({ ...e, node: nodes.get(e.typeName) }))
      .filter((e) => {
        if (!e.node) throw new Error(`export-doc: ledger type ${e.typeName} is not in the catalog`);
        return true;
      })
      .sort((a, b) => a.node.category.localeCompare(b.node.category) || a.node.name.localeCompare(b.node.name));

  out.push(`### Exports to React (${counts.translated})`);
  out.push('');
  const translated = byStatus('translated');
  const categories = [...new Set(translated.map((e) => e.node.category))];
  out.push('| Category | Nodes |');
  out.push('|---|---|');
  for (const c of categories) {
    out.push(`| ${escapeAngles(c)} | ${translated.filter((e) => e.node.category === c).map((e) => link(e.typeName)).join(', ')} |`);
  }
  out.push('');
  for (const [status, title] of [
    ['deferred', 'Not exported yet'],
    ['stubbed', 'Exported as a typed stub']
  ]) {
    const all = byStatus(status);
    if (!all.length) continue;
    out.push(`### ${title} (${all.length})`);
    out.push('');
    // Deprecated nodes share one reason (the ledger repeats it per row); they are listed together.
    const retired = all.filter((e) => e.node.deprecated);
    const rows = all.filter((e) => !e.node.deprecated);
    if (retired.length) {
      out.push(
        `**Deprecated (${retired.length}).** Nobody building today is offered these, and a project that still has one exports it as a named gap in the report: ${retired
          .map((e) => link(e.typeName))
          .join(', ')}.`
      );
      out.push('');
    }
    if (!rows.length) continue;
    out.push('| Node | Why |');
    out.push('|---|---|');
    for (const e of rows) {
      const why = escapeAngles(e.exemption || '—').replace(/\|/g, '\\|');
      out.push(`| ${link(e.typeName)} | ${why} |`);
    }
    out.push('');
  }
  const backend = byStatus('backend-only');
  out.push(`### Backend only (${backend.length})`);
  out.push('');
  out.push(`These run inside cloud functions, so the front end never sees them: ${backend.map((e) => link(e.typeName)).join(', ')}.`);
  out.push('');

  const content = out.join('\n');
  if (check) {
    const onDisk = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (onDisk !== content) {
      console.error('docs:export:check — stale. Run `npm run docs:export` and commit the result.');
      process.exit(1);
    }
    console.log('docs:export:check — clean.');
    return;
  }
  fs.writeFileSync(OUT, content);
  console.log(`docs:export — wrote ${path.relative(ROOT, OUT)}: ${Object.keys(app.files).length} example files, ${total} ledger rows.`);
}

main();
