// How each language writes a number.
const LOCALES = { en: 'en-GB' };
let lang = 'en';
export const num = (v) => v.toLocaleString(LOCALES[lang] ?? 'en-GB', { maximumFractionDigits: 2 });
export const setLanguage = (l) => (lang = TABLES[l] ? l : 'en');
export function t(key, vars = {}) {
  const s = TABLES[lang][key] ?? TABLES.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
