// OWN-034 §5 — the harness lane. A small model answers closed questions (prompts.mjs); the script builds the NodeGX
// app from fixed blocks (blocks.mjs) through the kit's own MCP server (mcp.mjs), so every write meets the real tools
// and their validation.
//
//   node harness.mjs --run g4-harness --model gemma4:e4b-it-qat --project <empty dir>
//   node harness.mjs --run blocks-control --answers control-answers.json --project <empty dir>   no model: the blocks alone
//   add --tuning T1 to apply the tuning rules named (prompts.mjs TUNINGS)
//   node harness.mjs --questions                                                                  (re)write questions.md
//
// The model: Ollama /api/chat, `format` = the schema, `think: false`, temperature 0, no history. Ollama must be idle
// (the OWN-031 session shares it) and the model is unloaded after (keep_alive 0). The ledger (runs/<run>/ledger.json)
// holds every call verbatim, the card, what was not built, and every MCP result that was not a success.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { open } from './mcp.mjs';
import * as P from './prompts.mjs';
import { BLOCKS, DAYS_JS, build, wants } from './blocks.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : d; };
const OLLAMA = process.env.OLLAMA_HOST || 'http://127.0.0.1:11434';
// --brief: the request file (default §3's brief.txt; H1 and H2 are brief-h1.txt, brief-h2.txt, run on the blocks unchanged).
const REQUEST = fs.readFileSync(path.resolve(HERE, opt('--brief', 'brief.txt')), 'utf8').trim();
const LOOK_PRESET = { clean: 'modern', bold: 'playful', warm: 'soft' };

// ─── questions.md ─────────────────────────────────────────────────────────────────────────────────────────────────
if (argv.includes('--questions')) {
  const card = { '…': 'the answers so far' };
  const show = (title, q) => `### ${title}\n\n\`\`\`text\n[system] ${P.SYSTEM}\n[user] ${q.user}\n\`\`\`\n\nschema: \`${JSON.stringify(q.schema)}\`\n`;
  const allRow = P.WORDS.row({ tick: true, del: true, ask: true, numbers: ['streak', 'best streak', 'done this week'] });
  const md = ['# OWN-034 — the harness lane\'s questions, verbatim', '',
    'Generated by `node harness.mjs --questions` from `prompts.mjs` and `blocks.mjs`. Every call is one system line and one user message, no history, `think: false`, temperature 0, Ollama `format` = the schema. `Decided so far` is the card of earlier answers, filled at run time. A question is asked only when an earlier answer makes it matter (in brackets).', '',
    '## What the script builds (the blocks)', '', ...BLOCKS.map((b) => `- ${b}`), '',
    '## Tuning rules (applied only when a run names them, `--tuning`)', '', ...Object.values(P.TUNINGS).map((t) => `- ${t}`), '',
    '## The decisions', '',
    show('the item', P.Q.noun(REQUEST, card)), show('per day', P.Q.perDay(REQUEST, card)), show('actions', P.Q.actions(REQUEST, card)),
    show('ask before delete (when the actions include delete)', P.Q.askBeforeDelete(REQUEST, card)), show('views', P.Q.views(REQUEST, card)),
    show('how many days (when the views include the last days)', P.Q.dayCount(REQUEST, card)), show('numbers', P.Q.numbers(REQUEST, card)), show('look', P.Q.look(REQUEST, card)),
    '## The words, one call per section', '',
    show('header', P.wordsQ('header', P.WORDS.header)(REQUEST, card)), show('add row (when the actions include add)', P.wordsQ('add row', P.WORDS.add)(REQUEST, card)),
    show('empty list', P.wordsQ('empty list', P.WORDS.empty)(REQUEST, card)), show('each row (fields only for the blocks chosen; all shown here)', P.wordsQ('each row', allRow)(REQUEST, card)),
    show('summary (when built)', P.wordsQ('summary', P.WORDS.summary)(REQUEST, card))
  ].join('\n');
  fs.writeFileSync(path.join(HERE, 'questions.md'), md);
  console.log('wrote questions.md');
  process.exit(0);
}

// ─── The run ──────────────────────────────────────────────────────────────────────────────────────────────────────
const RUN = opt('--run');
const TUNING = Object.fromEntries((opt('--tuning', '') || '').split(',').filter(Boolean).map((t) => [t, true]));
for (const t of Object.keys(TUNING)) if (!P.TUNINGS[t]) throw new Error(`unknown tuning ${t}`);
const MODEL = opt('--model');
const ANSWERS = opt('--answers');
// --random <seed>: the null model. Every menu question is answered at random from the same options (an array takes
// each option with p ½, redrawn until the schema's bounds hold); every free-text answer (the item's name, the words)
// is taken from control-answers.json. If this scores like a model, the grader cannot see the model's decisions.
const RANDOM = opt('--random');
const PROJECT = opt('--project');
if (!RUN || !PROJECT || (!MODEL && !ANSWERS && !RANDOM)) throw new Error('usage: node harness.mjs --run <name> (--model <ollama model> | --answers <card.json> | --random <seed>) [--brief <file>] --project <empty dir>');
if (fs.existsSync(PROJECT) && fs.readdirSync(PROJECT).length) throw new Error(`${PROJECT} exists and is not empty`);
const OUT = path.join(HERE, 'runs', RUN);
fs.mkdirSync(OUT, { recursive: true });

const t0 = Date.now();
const ledger = { run: RUN, model: MODEL || null, answers: ANSWERS || null, random: RANDOM ?? null, brief: opt('--brief', 'brief.txt'), request: REQUEST, project: PROJECT, tuning: Object.keys(TUNING).map((t) => P.TUNINGS[t]), startedAt: new Date().toISOString(), mcpBin: process.env.OWN034_MCP_BIN, card: {}, calls: [], notBuilt: [], mcp: [], result: null };
const writeLedger = () => fs.writeFileSync(path.join(OUT, 'ledger.json'), JSON.stringify(ledger, null, 1) + '\n');
process.on('uncaughtException', (e) => { ledger.result = { crashed: String(e?.stack || e) }; writeLedger(); console.error(e); unload().finally(() => process.exit(1)); });

async function unload() { if (MODEL) try { await fetch(`${OLLAMA}/api/generate`, { method: 'POST', body: JSON.stringify({ model: MODEL, keep_alive: 0 }) }); } catch {} }

if (MODEL) {
  const ps = await (await fetch(`${OLLAMA}/api/ps`)).json();
  if (ps.models?.length) throw new Error(`Ollama is busy (${ps.models.map((m) => m.name).join(', ')}); the OWN-031 session shares it`);
  ledger.digest = (await (await fetch(`${OLLAMA}/api/tags`)).json()).models.find((m) => m.name === MODEL)?.digest?.slice(0, 12);
}
const fixed = ANSWERS ? JSON.parse(fs.readFileSync(path.resolve(ANSWERS), 'utf8')) : null;
const WORDS_FROM = RANDOM ? JSON.parse(fs.readFileSync(path.join(HERE, 'control-answers.json'), 'utf8')) : null;
// xorshift, OWN-030's generator
const rnd = (() => { let x = Number(RANDOM) >>> 0 || 1; return () => { x ^= x << 13; x ^= x >>> 17; x ^= x << 5; return ((x >>> 0) % 1e9) / 1e9; }; })();
function randomAnswer(key, schema) {
  const out = {};
  for (const [k, p] of Object.entries(schema.properties)) {
    if (p.enum) out[k] = p.enum[Math.floor(rnd() * p.enum.length)];
    else if (p.type === 'array') { let pick; do pick = p.items.enum.filter(() => rnd() < 0.5); while (pick.length < (p.minItems ?? 0) || pick.length > (p.maxItems ?? 99)); out[k] = pick; }
    else out[k] = WORDS_FROM[key]?.[k] ?? '';
  }
  return out;
}

async function ask(key, q) {
  if (fixed) { const a = fixed[key]; ledger.calls.push({ key, fixed: true, answer: a }); return a; }
  if (RANDOM) { const a = randomAnswer(key, q.schema); ledger.calls.push({ key, random: true, answer: a }); console.log(`  ${key} → ${JSON.stringify(a).slice(0, 140)} (random)`); return a; }
  const t = Date.now();
  const r = await fetch(`${OLLAMA}/api/chat`, { method: 'POST', body: JSON.stringify({ model: MODEL, stream: false, format: q.schema, think: false, keep_alive: '10m',
    messages: [{ role: 'system', content: P.SYSTEM }, { role: 'user', content: q.user }], options: { temperature: 0, num_predict: 400, num_ctx: 4096 } }) });
  if (!r.ok) throw new Error(`ollama ${r.status}: ${(await r.text()).slice(0, 200)}`);
  const j = await r.json();
  let answer = null; try { answer = JSON.parse(j.message?.content ?? ''); } catch {}
  ledger.calls.push({ key, user: q.user, schema: q.schema, answer, raw: answer ? undefined : j.message?.content, tokensIn: j.prompt_eval_count, tokensOut: j.eval_count, truncated: j.done_reason === 'length' || undefined, ms: Date.now() - t });
  console.log(`  ${key} → ${JSON.stringify(answer).slice(0, 140)} (${j.prompt_eval_count}/${j.eval_count} tok, ${Date.now() - t} ms)`);
  return answer;
}

// The decisions. A question whose answer cannot change the build is not asked (e.g. ask-first without delete).
const card = ledger.card;
const take = async (key, q, field = key) => { const a = await ask(key, q); if (a && a[field] !== undefined) card[field] = a[field]; return a; };
await take('noun', P.Q.noun(REQUEST, card));
await take('perDay', P.Q.perDay(REQUEST, card));
const menu = TUNING.T1 ? Object.fromEntries(Object.entries(P.ACTIONS).filter(([k]) => k !== 'untick')) : P.ACTIONS;
await take('actions', P.Q.actions(REQUEST, card, menu));
if ((card.actions || []).includes('delete')) await take('askBeforeDelete', P.Q.askBeforeDelete(REQUEST, card));
await take('views', P.Q.views(REQUEST, card));
if ((card.views || []).includes('the last days per item')) await take('dayCount', P.Q.dayCount(REQUEST, card));
await take('numbers', P.Q.numbers(REQUEST, card));
await take('look', P.Q.look(REQUEST, card));
if (card.perDay === 'a number') ledger.notBuilt.push('a number per day: no block yet; built as done or not');

// The words, one call per section, each seeing the decisions (not the other sections' words).
const w = wants(card, TUNING);
const decided = { ...card };
card.words = {};
card.words.header = await ask('words.header', P.wordsQ('header', P.WORDS.header)(REQUEST, decided));
if (w.add) card.words.add = await ask('words.add', P.wordsQ('add row', P.WORDS.add)(REQUEST, decided));
card.words.empty = await ask('words.empty', P.wordsQ('empty list', P.WORDS.empty)(REQUEST, decided));
const rowFields = P.WORDS.row(w);
if (Object.keys(rowFields).length) card.words.row = await ask('words.row', P.wordsQ('each row', rowFields)(REQUEST, decided));
if (w.summary) card.words.summary = await ask('words.summary', P.wordsQ('summary', P.WORDS.summary)(REQUEST, decided));
await unload();
const modelMs = Date.now() - t0;
writeLedger();

// ─── The build, through the kit's MCP ─────────────────────────────────────────────────────────────────────────────
async function mcp(s, name, args) {
  const r = await s.call(name, args);
  ledger.mcp.push({ tool: name, isError: r.isError, ms: r.ms, chars: r.text.length, head: r.isError || /"severity":"(error|warning)"/.test(r.text) ? r.text.slice(0, 1500) : undefined });
  return r;
}
const s = await open(null);
const title = card.words.header?.title || 'Tracker';
const created = await mcp(s, 'create_project', {
  directory: PROJECT, name: title, request: REQUEST, summary: `A ${card.noun || 'item'} tracker kept on this device.`, audience: 'One person, on their own phone or computer.',
  objects: [{ name: card.noun || 'item', purpose: 'one thing the person tracks', fields: ['name', 'the days it was done'] }],
  pages: [{ name: 'Home', purpose: 'The list, the add row and today\'s ticks.' }], backend: { kind: 'none', description: 'None: everything is kept on this device, in a Global Store with Persist on.' }, agreed: false
});
if (created.isError) throw new Error(`create_project: ${created.text.slice(0, 400)}`);
await mcp(s, 'find_tools', { group: 'project' });
await mcp(s, 'find_tools', { group: 'theme' });
const preset = LOOK_PRESET[card.look] || 'modern';
await mcp(s, 'call_tool', { name: 'set_style_preset', arguments: { preset_id: preset } });
const sf = await mcp(s, 'call_tool', { name: 'write_script_file', arguments: { path: 'days.js', content: DAYS_JS } });
if (sf.isError) throw new Error(`write_script_file: ${sf.text.slice(0, 400)}`);

const home = (await mcp(s, 'get_component', { path: 'Pages/Home' })).json;
const pageId = home.nodes.find((n) => n.type === 'Page').id;
const vocab = (await mcp(s, 'get_style_vocabulary', {})).json;
const look = Object.fromEntries((vocab?.compositions || []).map((x) => [x.id, x.parameters]));
const app = build(card, pageId, look, TUNING);
ledger.notBuilt.push(...app.notBuilt);
const comps = app.components;
const plan = (await mcp(s, 'create_plan', { request: REQUEST, scroll: 'page', operations: comps.map((x) => ({
  kind: x.path === 'Pages/Home' ? 'update' : 'create', target: x.path, intent: x.intent,
  ...(x.inputs ? { inputs: x.inputs } : {}), ...(x.outputs?.length ? { outputs: x.outputs } : {}), ...(x.instantiates ? { instantiates: x.instantiates } : {})
})) })).json;
if (!plan?.planId) throw new Error(`create_plan: ${JSON.stringify(plan).slice(0, 400)}`);
const opFor = (target) => plan.operations.find((o) => o.target === target).id;
const staged = [];
for (const x of comps) {
  const r = await mcp(s, 'stage_plan_operation', { plan_id: plan.planId, operation_id: opFor(x.path), nodes: x.nodes, connections: x.connections, visual_roots: x.visual_roots });
  const diags = r.json?.validation?.diagnostics || r.json?.diagnostics || [];
  const readable = r.json?.error?.details?.readable || [];
  staged.push({ path: x.path, ok: !r.isError, readable: readable.map((t) => t.slice(0, 400)), errors: diags.filter((d) => d.severity === 'error').map((d) => `${d.code}: ${d.message}`.slice(0, 300)), warnings: diags.filter((d) => d.severity === 'warning').map((d) => `${d.code}: ${d.message}`.slice(0, 300)) });
}
ledger.staged = staged;
const ap = await mcp(s, 'apply_plan', { plan_id: plan.planId, render: 'summary' });
ledger.apply = ap.json ?? ap.text.slice(0, 3000);
const rr = await mcp(s, 'render_report', { out_dir: '.previews/shots', viewports: 'desktop,phone', scale: 0.5 });
ledger.render = rr.text.slice(0, 3000);
await s.close();

ledger.result = { applied: !ap.isError, stagedClean: staged.every((x) => x.ok && !x.errors.length), modelSeconds: Math.round(modelMs / 1000), minutes: +((Date.now() - t0) / 60000).toFixed(1),
  modelCalls: ledger.calls.filter((c) => !c.fixed && !c.random).length, unparsed: ledger.calls.filter((c) => !c.fixed && !c.random && !c.answer).length,
  tokensIn: ledger.calls.reduce((a, c) => a + (c.tokensIn || 0), 0), tokensOut: ledger.calls.reduce((a, c) => a + (c.tokensOut || 0), 0), preset, notBuilt: ledger.notBuilt };
writeLedger();
console.log(JSON.stringify({ staged, result: ledger.result }, null, 1));
